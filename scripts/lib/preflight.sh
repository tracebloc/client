# Ask install-client-helm.sh's engine rule which MySQL engine THIS host will get,
# echoing its "<engine> <reason>" verdict (backend#2047). The one amd64-only image
# left is mysql-client 5.7, so "will this host need emulation at all?" is a
# question only that rule can answer — and the arch gate below used to answer it
# itself, refusing fresh arm64 hosts the installer was about to serve natively on
# the multi-arch 8.4 engine.
#
# Two of the rule's inputs are `local`s of install_client_helm, which has not run
# yet: values_file (the sticky 8.4 opt-in) and TB_NAMESPACE (the per-release
# datadir path). Both are derived from that lib's own helpers, never restated
# here. `existing_id` genuinely cannot be known this early — helm hasn't been
# consulted — so an existing release can still read as fresh here; that residual
# case is caught by _assert_engine_runs_on_this_arch, which re-asks the same
# question once the engine is resolved for real.
#
# Fails CLOSED: if the engine rule isn't loaded we report 5.7, i.e. "no native
# path", and the refusal below stands. That is the honest answer rather than a
# guess — without the rule nothing here can tell whether this host holds 5.7
# data, and the chart's 8.4 default cannot open that.
_pf_mysql_engine_decision() {
  if ! declare -F _mysql_engine_decision >/dev/null 2>&1; then
    echo "5.7 no-engine-rule"; return 0
  fi
  # Dev mode (TRACEBLOC_VALUES_FILE): install_client_helm deploys the caller's file
  # AS-IS and resolves the engine straight from it (_devmode_engine_decision), NOT
  # via the auto rule below. Preflight MUST ask that same question, or the auto
  # rule's "8.4 fresh" green-lights a fresh arm64 host whose values file actually
  # pins the amd64-only 5.7 image — and the refusal then lands only at step e,
  # after the cluster is already provisioned (backend#2854; until chart 1.10.0 a
  # file SILENT on the engine did the same, the chart's default being 5.7). The
  # engine rule and this helper live in the same lib, so the guard above proves both
  # are loaded.
  if [[ -n "${TRACEBLOC_VALUES_FILE:-}" ]]; then
    _devmode_engine_decision; return 0
  fi
  # Both are read by _mysql_engine_decision through bash dynamic scope, which is
  # what SC2034 can't see (the documented false positive for scripts/lib/*.sh).
  # shellcheck disable=SC2034
  local values_file="" TB_NAMESPACE="${TB_NAMESPACE:-}"
  if declare -F _client_values_file >/dev/null 2>&1; then
    values_file="$(_client_values_file)"
  fi
  # UNCONDITIONALLY, exactly as install_client_helm does — not "only when unset".
  # That helper also SANITISES (DNS-1123), so an operator-supplied
  # TB_NAMESPACE="My Edge" becomes "my-edge" there. Gating this on emptiness left
  # the raw value here, and the two gates then probed different per-release
  # datadirs ("…/My Edge/mysql" vs "…/my-edge/mysql"): preflight would report a
  # native 8.4 pass and the late gate would refuse after cluster setup and
  # credential entry. Same rule, same inputs, or it is not the same question
  # (Bugbot, this PR).
  if declare -F _client_default_namespace >/dev/null 2>&1; then
    TB_NAMESPACE="$(_client_default_namespace)"
  fi
  _mysql_engine_decision
}

# The command that registers amd64 emulation (QEMU binfmt) here, for the arch
# refusal's remedy. Native k3s's containerd uses the host's own binfmt_misc handlers
# (/proc/sys/fs/binfmt_misc, which amd64_emulation_available reads), and the
# distro's QEMU package registers them.
_pf_binfmt_remedy() {
  if has apt-get; then
    printf 'sudo apt-get install -y qemu-user-static'
  elif has dnf; then
    printf 'sudo dnf install -y qemu-user-static'
  elif has zypper; then
    printf 'sudo zypper install -y qemu-linux-user'
  else
    printf "install your distribution's qemu-user-static package"
  fi
}

_pf_arch() {
  case "$ARCH" in
    x86_64|amd64) _pf_ok "Architecture: ${ARCH} (amd64)"; return 0 ;;
  esac
  # Non-amd64 (arm64/aarch64): the one remaining amd64-only image is the MySQL
  # 5.7 client, so whether this host needs emulation depends entirely on which
  # engine it gets — see _pf_mysql_engine_decision.
  if [[ -n "${TRACEBLOC_ALLOW_ARM64:-}" ]]; then
    warn "Architecture: ${ARCH} — proceeding (TRACEBLOC_ALLOW_ARM64 set); if this install keeps the amd64-only MySQL 5.7 engine it may crash without emulation."
    return 0
  fi
  # Ask the engine FIRST. Since chart 1.10.0 the default engine is the multi-arch
  # 8.4 (RFC-0150's exit), so emulation — Rosetta on a Mac, binfmt on Linux —
  # matters only to a client kept on 5.7 by its existing data or an explicit
  # request. Every branch below is about that 5.7 case; an 8.4 host needs none
  # of them, and naming Rosetta or binfmt to it would send it after a setting it
  # does not need (backend#2047's lesson, for the emulation that IS available).
  local _decision _engine _reason
  _decision="$(_pf_mysql_engine_decision)"
  _engine="${_decision%% *}"; _reason="${_decision#* }"
  if [[ "$_engine" == "8.4" ]]; then
    _pf_note "Architecture: ${ARCH} — running natively on the multi-arch MySQL 8.4 engine (no amd64 emulation needed)."
    return 0
  fi

  if _pf_on_mac_node; then
    # The macOS node runs amd64 images under Rosetta, which the node gets when this Mac
    # has it installed (mac-container.sh, --rosetta); there is no Docker setting to name.
    _pf_note "Architecture: ${ARCH} — the macOS node runs the amd64 client images under Rosetta when this Mac has it (softwareupdate --install-rosetta)."
    return 0
  fi
  if amd64_emulation_available; then
    _pf_note "Architecture: ${ARCH} — amd64 emulation (QEMU binfmt) available; client images run emulated (slower)."
    return 0
  fi
  # No emulation, and the engine asked above is not 8.4: this host would run the
  # amd64-only 5.7 image, which it can't.
  PF_HARD_FAIL=$(( ${PF_HARD_FAIL:-0} + 1 ))
  # An unusable TB_MYSQL_ENGINE arrives as engine="invalid", reason=<the value> —
  # so it is checked on the ENGINE field, not inside the reason case below.
  # "Cannot tell" is a finding, not a pass: the engine, and therefore whether this
  # host can run it, is undecidable.
  if [[ "$_engine" == "invalid" ]]; then
    _pf_fail_line "TB_MYSQL_ENGINE='${_reason}' is not 'auto', '5.7' or '8.4', so the MySQL engine for this ${ARCH} host can't be determined."
    hint "Fix: set TB_MYSQL_ENGINE=auto (or 8.4 for the native multi-arch engine) and re-run."
    # No TRACEBLOC_ALLOW_ARM64 hint here: it would only defer this failure to
    # _resolve_mysql_engine, which refuses the value outright.
    return 0
  fi
  case "$_reason" in
    existing-datadir)
      # Say WHY: the blocker is the datadir format, not this machine's CPU. An
      # amd64 VM would not help — the data is here.
      _pf_fail_line "Existing MySQL 5.7 data on this host pins the install to the MySQL 5.7 engine, and that image is amd64-only — it can't run on ${ARCH}."
      hint "This is a data-format constraint, not an architecture one: MySQL 8.4 runs natively on ${ARCH}, but it cannot open a 5.7-format datadir (MySQL upgrades only in stages, 5.7 → 8.0 → 8.4)."
      hint "Keep this data — enable amd64 emulation, then re-run:"
      hint "  $(_pf_binfmt_remedy)"
      hint "Or start fresh on the native engine — install into an empty data directory:"
      hint "  --data-dir=/path/to/new/empty/dir" ;;
    explicit)
      _pf_fail_line "TB_MYSQL_ENGINE=5.7 was requested, and the MySQL 5.7 image is amd64-only — it can't run on ${ARCH}."
      hint "Drop TB_MYSQL_ENGINE (or set TB_MYSQL_ENGINE=8.4) to use the native multi-arch 8.4 engine — fresh data directories only."
      hint "To keep 5.7, enable amd64 emulation and re-run:"
      hint "  $(_pf_binfmt_remedy)" ;;
    values-file)
      # Dev mode (caller-supplied values file) whose images.mysqlClient block
      # renders the amd64-only 5.7 image, or an image this check cannot name.
      # Two fixes: take the native 8.4 engine (fresh data only), or enable emulation.
      _pf_fail_line "The supplied values file pins the amd64-only MySQL 5.7 engine (or an image this check can't name), and that image can't run on ${ARCH}."
      hint "Use the native multi-arch 8.4 engine: drop images.mysqlClient from your values file to take the chart default, or pin images.mysqlClient.tag: \"8.4\" + digest: \"\" — fresh data directories only."
      hint "Or enable amd64 emulation and re-run:"
      hint "  $(_pf_binfmt_remedy)" ;;
    *)
      # Includes `no-engine-rule` (the fail-closed answer when the lib holding
      # the rule isn't loaded). Generic, and still emulation-shaped: without the
      # rule there is no 8.4 opt-in to reach.
      _pf_fail_line "Architecture: ${ARCH} — this install needs the amd64-only MySQL 5.7 image and can't run here."
      hint "Fix: enable amd64 emulation and re-run:"
      hint "  $(_pf_binfmt_remedy)" ;;
  esac
  hint "  (or set TRACEBLOC_ALLOW_ARM64=1 to proceed anyway)"
  return 0
}

_pf_cpu() {
  local n; n="$(_pf_ncpu)"
  if [[ -z "$n" ]]; then warn "CPU: couldn't determine core count (skipping)."; return 0; fi
  # CPU is warn-only: starvation throttles (and can trip mysql InnoDB lock-wait
  # timeouts) but doesn't OOM-kill, and the chart deliberately omits limits.cpu.
  if [[ "$n" -lt "$PF_MIN_CPU" ]]; then
    warn "CPU: ${n} core(s) — below the ${PF_MIN_CPU}-core minimum; mysql may hit lock-wait timeouts. ${PF_REC_CPU}+ recommended to train."
  elif [[ "$n" -lt "$PF_REC_CPU" ]]; then
    warn "CPU: ${n} cores — fine to run; ${PF_REC_CPU}+ recommended to train locally."
  else
    _pf_ok "CPU: ${n} cores"
  fi
  return 0
}

_pf_memory() {
  # Two truths, two lines (#417): the machine's RAM (a hardware fact — the gate
  # runs on it; on native Linux the daemon sees all host RAM so the gate is
  # unchanged) and, when a runtime VM is up with a meaningfully smaller budget
  # (WSL2, or the macOS node's VM), the runtime's actual budget on its own
  # line with achievable advice. The old single line flip-flopped between the
  # two across re-runs of the SAME installer on the SAME machine — "16 GB
  # (host)" cold, "6 GB (Docker VM)" warm — depending only on whether Docker
  # happened to already be running.
  local host_kb rt_kb rt_gb kb gb mib floor_mib warn_mib label rec_gb warn_gb budget="Docker budget"
  ! _pf_on_mac_node || budget="node"   # k3s in Apple's VM: no Docker (2.1)
  host_kb="$(_pf_host_mem_kb)"
  rt_kb="$(_pf_runtime_mem_kb)"
  # Same converter as $gb below: this feeds the "is the VM meaningfully smaller
  # than the machine" comparison, and grading one side grace-adjusted against a
  # raw other side is the exact mistake this PR keeps rediscovering.
  [[ -n "$rt_kb" ]] && rt_gb="$(_pf_display_gb_from_mib "$(( rt_kb / 1024 ))")"
  # Gate on the machine; only if the host is unreadable fall back to the VM
  # budget (rare — /proc/meminfo and hw.memsize are near-universal).
  kb="$host_kb"; label="machine"
  if [[ -z "$kb" && -n "$rt_kb" ]]; then kb="$rt_kb"; label="Docker VM"; fi
  if [[ -z "$kb" ]]; then warn "Memory: couldn't determine total RAM (skipping)."; return 0; fi
  mib=$(( kb / 1024 ))
  # Same grace-adjusted figure _pf_runtime_mem_status reports, so one budget never
  # appears as two different numbers across the two messages (Bugbot #445 r4).
  gb="$(_pf_display_gb_from_mib "$mib")"
  # Compare in MiB with a 64 MiB grace so a VM that reports e.g. 4 GiB a hair under
  # 4*1024^3 (a VM's guest MemTotal) doesn't floor to 3 GB and false-trip the gate.
  # Tolerance must match the grace already applied to the SHOWN figure above, or
  # the two disagree: a 5 GB VM whose MemTotal sits a few hundred MiB under the
  # configured size displayed as "5 GB" while a 64 MiB tolerance graded it
  # sub-floor, producing "Memory: 5 GB — below the 5 GB the client needs"
  # (Bugbot #445 r5, High). PF_VM_MEM_GRACE_MIB is the same tolerance
  # _pf_runtime_mem_status uses for its own floor and warn tests, so all three
  # now agree on where the boundaries are.
  # The DERIVED run floor replaces the typed one (Linux: backend#5601; the Mac and
  # Windows VM: client-dev#2105) -- a machine under it installed "fine" and then
  # could never schedule a single run. On Linux it HARD-fails here in tenths.
  floor_mib="$(_pf_vm_floor_mib)"
  local run_floor_mib="" floor_gb native_linux=0
  floor_gb="$(_pf_budget_floor_gb)"
  # NATIVE Linux is the family, not OS=Linux: WSL2 reports OS=Linux but its VM is
  # graded on the Windows floor and warns here (client-dev#2124, Bugbot), exactly
  # as _pf_runtime_run_floor_mib and the host-too-small arm below already do.
  [[ "$(_pf_run_floor_family 2>/dev/null)" == linux ]] && native_linux=1
  if [[ "$native_linux" == 1 ]] && run_floor_mib="$(_pf_run_floor_mib)"; then
    :
  else
    run_floor_mib=""
  fi
  warn_mib=$(( PF_WARN_MEM_GB * 1024 - PF_VM_MEM_GRACE_MIB ))
  # SHOWN figures clamped to physical RAM so no hint asks for more than the machine
  # has (#428): "raise to 16 GB" on a 16 GB Mac is impossible.
  rec_gb="$(_pf_clamp_mem_gb "$PF_REC_MEM_GB")"
  warn_gb="$(_pf_clamp_mem_gb "$PF_WARN_MEM_GB")"

  if [[ "$mib" -lt "$floor_mib" ]]; then
    if [[ -n "$run_floor_mib" ]]; then
      _pf_fail_line "Memory: only $(_pf_tenths_gb "$mib" down) GB (${label}) — this machine cannot fit one training run beside the tracebloc platform; need ≥ $(_pf_tenths_gb "$run_floor_mib" up) GB."
      PF_HARD_FAIL=$(( ${PF_HARD_FAIL:-0} + 1 ))
      # Unclamped on purpose: the remedy is a LARGER machine, so the clamp to this
      # one's RAM (#428) would ask for less than the floor just named.
      hint "Use a machine (or resize the VM) with ≥ $(_pf_tenths_gb "$run_floor_mib" up) GB of RAM; ${PF_REC_MEM_GB} GB to train locally. Then re-run."
    elif [[ "$native_linux" == 1 ]]; then
      _pf_fail_line "Memory: only ${gb} GB (${label}) — need ≥ ${PF_MIN_MEM_GB} GB to run the tracebloc client."
      PF_HARD_FAIL=$(( ${PF_HARD_FAIL:-0} + 1 ))
      hint "Resize the VM (or free memory) to ≥ ${warn_gb} GB; ${rec_gb} GB to train locally. Then re-run."
    else
      # Mac/Win: the MACHINE itself is below the floor — no Docker setting can
      # fix that, so don't offer a resize remedy here. Warn (don't block); the
      # create_cluster re-check sees the real VM size and HARD-FAILS a sub-floor
      # VM (#428), including the honest "use a larger machine" case.
      warn "Memory: ${gb} GB (${label}) — $(_pf_vm_floor_words)."
    fi
  elif [[ "$(_pf_run_floor_family 2>/dev/null)" != linux && "$label" == "machine" ]] \
     && _pf_host_too_small_for_floor "$(_pf_host_mem_gb)"; then
    # Above the bare floor, but not by enough to give Docker the floor AND leave
    # the OS its reserve. Saying "enough to run" here contradicted the budget
    # line's "use a larger machine" in the same preflight (Bugbot #445 r3). On
    # native Linux the daemon sees host RAM directly, so the reserve arithmetic
    # does not apply and that path keeps the original wording. Gated on the
    # floor family, not on OS: WSL2 reports OS=Linux but is graded on the
    # Windows VM floor, and _pf_clamp_mem_gb would otherwise lift its "can spare"
    # figure above the host's own RAM (client-dev#2124, Bugbot).
    warn "Memory: ${gb} GB (${label}) — the client needs a ${floor_gb} GB ${budget} and the OS needs ~${PF_OS_RESERVE_GB} GB, so this machine is below the practical minimum of about $(( floor_gb + PF_OS_RESERVE_GB )) GB. Free up memory or use a larger machine."
  elif [[ "$mib" -lt "$warn_mib" ]]; then
    # The DERIVED budget, not its clamp (Bugbot on client#1085) — the same rule as
    # _pf_runtime_mem_status. AND NO
    # "N GB recommended to train" BELOW THE NEED (Bugbot, round 2): for host RAM
    # this branch fires only when gb < PF_WARN_MEM_GB, so the clamped
    # recommendation (gb − reserve) is ALWAYS below the budget the sentence has
    # just named — "needs 9 GB; 6 GB recommended to train" on every 8 GB host.
    # Such a host cannot be tuned into a training box; say that. The figure
    # survives only where the clamp did not bite (an unreadable host graded on
    # its Docker VM), where it is honest.
    if (( rec_gb < PF_WARN_MEM_GB )); then
      # Never the floor-lifted clamp: under WSL2 the host arm above no longer
      # catches a small VM, and _pf_clamp_mem_gb lifts its cap to the VM floor, so
      # an 8 GB VM read "can spare at most 9 GB" (client-dev#2124, Bugbot) -- nor
      # the VM less a Windows reserve, which read 6 (client-dev#2158): _pf_spare_gb.
      local spare_gb
      spare_gb="$(_pf_spare_gb "$rec_gb" "$gb")"
      warn "Memory: ${gb} GB (${label}) — enough to run the client; the smallest training run (4 GiB) needs a ${PF_WARN_MEM_GB} GB budget once the kubelet reservation, k3s addons, control plane and CronJobs are counted, and this machine can spare at most ${spare_gb} GB, so $(_pf_spare_rung_words)."
    else
      warn "Memory: ${gb} GB (${label}) — enough to run the client; the smallest training run (4 GiB) needs a ${PF_WARN_MEM_GB} GB budget once the kubelet reservation, k3s addons, control plane and CronJobs are counted. ${rec_gb} GB of RAM recommended to train locally."
    fi
  else
    _pf_ok "Memory: ${gb} GB (${label})"
  fi

  # Docker's budget as its own line — only when a runtime is up AND its budget is
  # meaningfully smaller than the machine (the VM case). On native Linux the
  # daemon sees host RAM, so this would just repeat the line above.
  if [[ -n "$rt_kb" && "$label" == "machine" ]] && (( rt_gb + 1 < gb )); then
    _pf_runtime_mem_status $(( rt_kb / 1024 ))
  fi

  # Linux: even when total is fine, a busy shared VM may have little free RAM now.
  if [[ "$OS" == "Linux" ]]; then
    local avail_kb avail_gb
    avail_kb="$(_pf_avail_mem_kb)"
    if [[ -n "$avail_kb" ]]; then
      avail_gb=$(( avail_kb / 1024 / 1024 ))
      if [[ "$avail_gb" -lt "$PF_MIN_MEM_GB" ]]; then
        warn "Memory: only ${avail_gb} GB available right now (other workloads are using this machine) — the client needs ~${PF_MIN_MEM_GB} GB free to start."
      fi
    fi
  fi
  return 0
}

# Re-evaluate memory once Docker is confirmed up. Preflight runs before Docker
# starts (install-k8s.sh), so on macOS/Windows the first read was host RAM, not the
# Docker VM's smaller budget. Called from create_cluster (k3d.sh) — the first
# point `docker info` is reliably up on every OS. A sub-FLOOR VM HARD-FAILS here with
# the exact fix (#428): it will OOM-crashloop the client, so proceeding is worse than
# the jarring stop the WARN path used to avoid. A between-floor-and-warn VM still only
# warns (the user has waited for Docker; it can run, just tightly).
_pf_recheck_runtime_mem() {
  [[ -n "${TRACEBLOC_SKIP_PREFLIGHT:-}" ]] && return 0
  # rec_gb is deliberately not read here: the between-floor-and-warn copy (and its
  # "N GB to train" figure) now lives solely in _pf_runtime_mem_status.
  local kb gb mib warn_gb; kb="$(_pf_runtime_mem_kb)"
  [[ -z "$kb" ]] && return 0          # daemon still not reporting — nothing to add
  mib=$(( kb / 1024 ))
  # Same converter the status line uses, so the hard-fail can never quote a
  # different size for the same budget (Bugbot #445 r4 — this fix was written then
  # but landed in the wrong function, because the two-line pattern it anchored on
  # existed in _pf_memory too and the replace took the first match).
  gb="$(_pf_display_gb_from_mib "$mib")"
  warn_gb="$(_pf_clamp_mem_gb "$PF_WARN_MEM_GB")"
  # Native Linux: the budget is graded against the derived run floor, not the typed
  # one (client-dev#2113) -- the same floor _pf_memory holds the host to. A Mac or
  # WSL2 VM: its own family's floor (client-dev#2105).
  local rt_fam floor_mib run_floor_mib=""
  rt_fam="$(_pf_runtime_floor_family)"
  floor_mib="$(_pf_vm_floor_mib "$rt_fam")"
  if run_floor_mib="$(_pf_runtime_run_floor_mib)"; then floor_mib="$run_floor_mib"; else run_floor_mib=""; fi
  if [[ "$mib" -lt "$floor_mib" ]]; then
    # The REAL VM size is now known and it's below the floor — the client OOMs. Stop.
    # Tolerance is PF_VM_MEM_GRACE_MIB (not 64): the guest MemTotal is a few hundred MiB
    # under the configured size, so a VM set to exactly the documented floor still
    # passes here rather than hard-failing on the guest shortfall (#513 reviewer).
    # If the HOST is too small to ever give the VM the floor (physical − reserve <
    # floor), no resize helps — say so plainly instead of a remedy that repeats an
    # unachievable size (#428 Bugbot).
    local phys_gb; phys_gb="$(_pf_host_mem_gb)"
    # Through the SHARED predicate, and on every OS. Two divergences lived here
    # (Bugbot #445 r7, High): the arithmetic was inlined rather than calling
    # _pf_host_too_small_for_floor, and the branch was gated OS != Linux while
    # _pf_runtime_mem_status applies it everywhere. On a warm Linux install with a
    # sub-floor cgroup/VM budget, preflight therefore said "use a larger machine"
    # and this hard-fail then advised raising Docker to a size that machine cannot
    # give — the same remedy contradiction, one OS gate apart.
    if _pf_host_too_small_for_floor "$phys_gb"; then
      if [[ -n "$run_floor_mib" ]]; then
        error "This machine has ${phys_gb} GB RAM — too little for tracebloc: one training run needs a $(_pf_runtime_run_target_gb "$run_floor_mib") GB Docker budget beside the tracebloc platform, more than this machine has. Use a larger machine."
      else
        local floor_gb; floor_gb="$(_pf_budget_floor_gb)"
        error "This machine has ${phys_gb} GB RAM — too little for tracebloc: the client needs a ${floor_gb} GB Docker budget and the OS needs ~${PF_OS_RESERVE_GB} GB, so about $(( floor_gb + PF_OS_RESERVE_GB )) GB physical is the practical minimum. Use a larger machine."
      fi
    elif [[ -n "$run_floor_mib" ]]; then
      error "Docker has only $(_pf_tenths_gb "$mib" down) GB — below the $(_pf_tenths_gb "$run_floor_mib" up) GB one training run needs beside the tracebloc platform; no run can schedule. Raise the VM/cgroup limit (or free memory) to ≥ $(_pf_runtime_run_target_gb "$run_floor_mib") GB, then re-run."
    else
      error "Docker has only ${gb} GB — $(_pf_vm_floor_words "$rt_fam"). Free memory (or raise the VM) to ≥ ${warn_gb} GB, then re-run."
    fi
  fi
  # Between floor and warn: warn only, through the ONE shared copy so this and the
  # Step-1 preflight line can no longer diverge in wording OR in threshold — the
  # cold-install path (Docker starts mid-run, the common case) previously got its
  # own text with no Linux cgroup hint, and graded against
  # the raw PF_WARN_MEM_GB while preflight used the clamped target (Bugbot #445 r2).
  # Skipped when preflight ALREADY reported this same budget on a warm re-run. The
  # latch suppresses a DUPLICATE WARNING only, and is deliberately tested here
  # rather than at the top of the function so it can never gate the hard-fail above.
  if [[ -z "${PF_RUNTIME_MEM_WARNED:-}" ]]; then
    _pf_runtime_mem_status "$mib" quiet_ok
  fi
  return 0
}

_pf_disk() {
  if _pf_on_mac_node; then _pf_disk_mac_node; return 0; fi
  if [[ "${TRACEBLOC_SUBSTRATE_RESOLVED:-}" == "k3s" ]]; then _pf_disk_k3s; return 0; fi
  # Any other substrate was refused before preflight (tb_substrate_resolve): there is
  # no disk of its to grade.
  return 0
}

# On macOS, native k3s runs in a VM on Apple's runtime (slim client 2.1), and all it
# writes lands under the runtime's app root (mac-container.sh's _mac_ct_app_root): the
# images, the kernel, and the node's volume, a sparse image that takes only what is
# written. That is one disk, graded against the same floors as Linux's
# (PF_MIN_DISK_GB, PF_WARN_DISK_GB). It does not exist before the install, so it is
# measured on its nearest existing parent (_pf_mac_node_disk_at), as the summary line
# measures it. A re-run gets no credit for the images it reuses: nothing has measured
# them on a Mac yet, so the floor counts them as on a fresh one. Without mac-container.sh
# (a stale bootstrap), where the app root is cannot be told, and the line says so.
_pf_mac_node_disk_at() {
  local root at
  declare -F _mac_ct_app_root >/dev/null 2>&1 || return 1
  root="$(_mac_ct_app_root 2>/dev/null)" || return 1
  [[ "$root" == /* ]] || return 1
  at="$(_pf_nearest_existing "$root")"; [[ -n "$at" ]] || at="/"
  printf '%s\t%s' "$at" "$root"
}
# Under hostpath the training data is not in the node's volume but in the hostPath
# folder on this Mac, which the node mounts (_mac_ct_node_mounts): a second line grades
# that folder's disk, as _pf_disk_k3s grades HOST_DATA_DIR for native k3s's hostpath.
# Under node-local the job data is in the job-data folder (_mac_ct_job_data_dir) when the
# install keeps one, and the second line grades that folder's disk.
_pf_disk_mac_node() {
  local both tab=$'\t' root at
  both="$(_pf_mac_node_disk_at)" \
    || { warn "Disk: couldn't tell where Apple's container runtime will keep the node (skipping)."; return 0; }
  _pf_disk_grade "${both%%"$tab"*}" "the node's images and volume (${both#*"$tab"})"
  # node-local: the job data is in the job-data folder on this Mac (client-dev#2320).
  if [[ "${TB_STORAGE_MODE:-node-local}" != "hostpath" ]]; then
    root=""
    if declare -F _mac_ct_job_data_dir >/dev/null; then root="$(_mac_ct_job_data_dir)"; fi
    [[ -n "$root" ]] || return 0
    at="$(_pf_nearest_existing "$root")"; [[ -n "$at" ]] || at="/"
    _pf_disk_grade "$at" "the job data (${root})"
    return 0
  fi
  root="$(_hostpath_root)"; root="${root:-${HOST_DATA_DIR:-}}"
  at="$(_pf_nearest_existing "$root")"; [[ -n "$at" ]] || at="/"
  _pf_disk_grade "$at" "the hostPath volumes (${root})"
}

# Native k3s (TRACEBLOC_SUBSTRATE_RESOLVED=k3s) keeps nothing under Docker's root. Its disk is two
# paths, each named in the line, against the same floors as k3d's (PF_MIN_DISK_GB,
# PF_WARN_DISK_GB):
#   - k3s's data path (/var/lib/rancher/k3s): the images, containerd and its state;
#   - the storage path, where local-path keeps the volumes: k3s's default under the
#     data path, or the operator's data dir (_native_k3s_storage_path, k3s.sh).
# Neither exists before the install, so each is measured on its nearest existing
# parent, and the line names the directory it measured. Two paths measured on the
# same directory are one disk: one line names both, and the floor is asked once.
#
# On a node-local re-run the storage path is the one config.yaml froze, which only
# root reads.
# This is the first reader of a run and runs in the main shell, so when the reader
# needs the password it asks here, once, through preflight_sudo (whose keepalive the
# install then keeps). A config.yaml that cannot be read refuses: where the volumes
# live is not something to guess.
#
# A re-run of the k3s this installer set up already holds its images, and reuses
# them: the floor is the room a k3s install needs, and those bytes are part of it,
# not a claim on the free space left. So on such a re-run each line on the image
# store's filesystem counts them back (_pf_k3s_reused_kb). Measured on the k3s
# journey: 13 GB free before the first install, 9 to 10 GB at the re-run's
# preflight, where an unchanged re-run pulls nothing ("No change detected").
#
# A consented move off k3d (D10) frees space the same way, later in step a:
# reinstall_offboard_k3d runs after this check and removes the k3d cluster's
# volumes, 2.9 GB of them on the measured host (client-dev#1816). The check stays
# where it is, before the offboard (client-dev#1805), so each line counts back the
# volumes on its own disk (_pf_k3d_offboard_volumes). An estimate that cannot be
# read counts nothing, and the line says so.
_pf_disk_k3s() {
  local data="$TB_K3S_DATA_PATH" storage at_data at_storage rc=0 reused store_at why="" freed="" frc=0
  # hostpath (client-dev#1782): the volumes are the chart's hostPath PVs under
  # HOST_DATA_DIR (an installed release's own root, _hostpath_root), so that is the
  # disk the training data needs. The storage path config.yaml names holds none of
  # it, so config.yaml is not read at all: a file this check then ignores must not
  # refuse the run, or ask for the password (Bugbot on #1790). Its drift is no news
  # here either. rc stays 0, so the reader's branches below are node-local's.
  if [[ "${TB_STORAGE_MODE:-node-local}" == "hostpath" ]]; then
    storage="$(_hostpath_root)"; storage="${storage:-${HOST_DATA_DIR:-}}"
  else
    storage="$(_native_k3s_storage_path)" || rc=$?
  fi
  if [[ "$rc" -eq 4 ]]; then
    # A host prepared for this user that cannot be adopted yet (1.1g): a password
    # would end in preflight_sudo's Docker wording, and is not what is missing. Say
    # what is, with the remedy step b gives (_native_k3s_prepare_host_remedy).
    why="$(_native_k3s_prepared_for_me)" || true
    _pf_fail_line "Disk: where this machine's k3s keeps its volumes is in ${TB_K3S_CONFIG_PATH}, which you cannot read yet."
    PF_HARD_FAIL=$(( ${PF_HARD_FAIL:-0} + 1 ))
    hint "$(_native_k3s_prepare_host_remedy "$why")"
    return 0
  fi
  if [[ "$rc" -eq 3 ]]; then
    preflight_sudo
    rc=0; storage="$(_native_k3s_storage_path)" || rc=$?
  fi
  if [[ "$rc" -ne 0 ]]; then
    _pf_fail_line "Disk: couldn't read ${TB_K3S_CONFIG_PATH}, so where this machine's k3s keeps its volumes can't be told."
    PF_HARD_FAIL=$(( ${PF_HARD_FAIL:-0} + 1 ))
    hint "Check it with 'sudo cat ${TB_K3S_CONFIG_PATH}', then re-run."
    return 0
  fi
  if [[ "${TB_STORAGE_MODE:-node-local}" != "hostpath" ]]; then
    _native_k3s_storage_drift_warn
  fi
  at_data="$(_pf_nearest_existing "$data")"; [[ -n "$at_data" ]] || at_data="/"
  at_storage="$(_pf_nearest_existing "$storage")"; [[ -n "$at_storage" ]] || at_storage="/"
  reused="$(_pf_k3s_reused_kb)"; store_at=""
  # The store's disk is read as root, like its size: k3s creates its agent/ directory
  # 0700 (pkg/agent/run.go, MkdirAll(agentDir, 0700)), so this user's df cannot reach
  # the store below it, and the credit came out 0 on every re-run.
  # A df that fails leaves store_at empty (no credit); as the last command of a && list
  # its status would abort the installer under set -e, so the || keeps it fail-closed.
  if [[ "$reused" -gt 0 ]]; then
    store_at="$(_pf_mount_of "${TB_K3S_DATA_PATH}/agent/containerd" sudo)" || store_at=""
  fi
  freed="$(_pf_k3d_offboard_volumes)" || frc=$?
  if [[ "$at_data" == "$at_storage" ]]; then
    _pf_disk_grade "$at_data" "k3s's data (${data}) and the training data (${storage})" "$(_pf_k3s_credit_on "$at_data" "$store_at" "$reused")" "$(_pf_k3d_freed_on "$at_data" "$frc" "$freed")"
  else
    _pf_disk_grade "$at_data" "k3s's data (${data})" "$(_pf_k3s_credit_on "$at_data" "$store_at" "$reused")" "$(_pf_k3d_freed_on "$at_data" "$frc" "$freed")"
    _pf_disk_grade "$at_storage" "the training data (${storage})" "$(_pf_k3s_credit_on "$at_storage" "$store_at" "$reused")" "$(_pf_k3d_freed_on "$at_storage" "$frc" "$freed")"
  fi
  return 0
}

# _pf_k3s_reused_kb -- on a re-run of the k3s this installer set up, the KB its image
# store holds (TB_K3S_DATA_PATH/agent/containerd, which the re-run reuses); 0 otherwise.
# "Set up by this installer" is the install record listing `k3s-install`. The credit
# is given only when it is known: no record, a record that cannot be read, a root that
# cannot answer without a prompt, or a store du cannot measure all give 0, and the
# floor then counts the store as on a fresh host (fail closed). A user on a host
# prepared for them (1.1g) gets 0 the same way, on purpose: the store sits below
# k3s's 0700 agent/, so only root can measure it, and prepared mode asks for no root.
_pf_k3s_reused_kb() {
  local rec kb
  rec="$(tb_record_path)"
  if [[ ! -f "$rec" || ! -r "$rec" ]] || ! grep -qF '"kind": "k3s-install"' "$rec" 2>/dev/null; then
    echo 0; return 0
  fi
  _native_k3s_root_ready || { echo 0; return 0; }
  kb="$(sudo du -sxk "${TB_K3S_DATA_PATH}/agent/containerd" 2>/dev/null | awk 'NR==1 {print $1}')"
  [[ "$kb" =~ ^[0-9]+$ ]] || kb=0
  echo "$kb"
}

# _pf_mount_of DIR [CMD...] -- the mount point of the filesystem holding DIR (POSIX df),
# so two directories can be told to share a disk; empty when df cannot answer. CMD
# (sudo) runs the df, for a directory only root can reach.
_pf_mount_of() { local d="$1"; shift; "$@" df -Pk "$d" 2>/dev/null | awk 'NR==2 {print $6}'; }

# _pf_k3s_credit_on DIR STORE_MOUNT KB -- KB when DIR is on the image store's
# filesystem, else 0. An unknown mount on either side is 0: the credit is not guessed.
_pf_k3s_credit_on() {
  local m
  [[ "$3" -gt 0 && -n "$2" ]] || { echo 0; return 0; }
  m="$(_pf_mount_of "$1")"
  if [[ -n "$m" && "$m" == "$2" ]]; then echo "$3"; else echo 0; fi
}

# _pf_k3d_offboard_volumes -- on a consented move off k3d, one "KB MOUNT" line per
# volume of tracebloc's k3d cluster (TRACEBLOC_REINSTALL_CLUSTER), which
# reinstall_offboard_k3d removes: its size and the mount point of its filesystem.
# 1 and nothing when this run does not offboard. 2 and nothing when the estimate
# cannot be read: Docker does not answer, no container carries the cluster's label,
# root would need the password, or a volume's size or disk cannot be read. The
# credit is then 0 (fail closed). The offboard's own removal list is what counts:
# the cluster's volumes. Its node images stay. The containers' own layers are
# removed but not counted, so the estimate errs low, which can only refuse more.
# Each volume is measured as root: Docker's data root is root's.
_pf_k3d_offboard_volumes() {
  local name="${TRACEBLOC_REINSTALL_CLUSTER:-}" ids vols v mp kb m t="${TB_DOCKER_PROBE_TIMEOUT:-10}" out=""
  [[ "${TRACEBLOC_REINSTALL_DECISION:-}" == "offboard" && "${TB_K3D_REINSTALL:-}" == "offboard" ]] || return 1
  [[ -n "$name" ]] || return 2
  _native_k3s_root_ready || return 2
  ids="$(_bounded "$t" docker ps -aq --filter "label=k3d.cluster=${name}" 2>/dev/null)" || return 2
  [[ -n "$ids" ]] || return 2
  # shellcheck disable=SC2086  # one argument per container ID
  vols="$(_bounded "$t" docker inspect --format '{{range .Mounts}}{{if eq .Type "volume"}}{{.Name}} {{end}}{{end}}' $ids 2>/dev/null)" || return 2
  vols="$(printf '%s' "$vols" | tr ' ' '\n' | sort -u)"
  [[ -n "$vols" ]] || return 2
  while IFS= read -r v; do
    [[ -n "$v" ]] || continue
    mp="$(_bounded "$t" docker volume inspect --format '{{.Mountpoint}}' "$v" 2>/dev/null)" || return 2
    [[ -n "$mp" ]] || return 2
    kb="$(sudo du -sxk "$mp" 2>/dev/null | awk 'NR==1 {print $1}')"
    [[ "$kb" =~ ^[0-9]+$ ]] || return 2
    m="$(_pf_mount_of "$mp" sudo)" || m=""
    [[ -n "$m" ]] || return 2
    out="${out}${kb} ${m}"$'\n'
  done <<<"$vols"
  printf '%s' "$out"
}

# _pf_k3d_freed_on DIR RC VOLUMES -- what the offboard frees on DIR's disk, from
# _pf_k3d_offboard_volumes' status RC and its VOLUMES: the KB of the volumes on DIR's
# filesystem; "none" when this run does not offboard (RC 1); "unknown" when the
# estimate cannot be read (RC 2), or DIR's own disk cannot.
_pf_k3d_freed_on() {
  local m kb mount sum=0
  case "$2" in 0) ;; 1) echo none; return 0 ;; *) echo unknown; return 0 ;; esac
  m="$(_pf_mount_of "$1")"
  [[ -n "$m" ]] || { echo unknown; return 0; }
  while read -r kb mount; do
    [[ -n "$kb" && "$mount" == "$m" ]] && sum=$(( sum + kb ))
  done <<<"$3"
  echo "$sum"
}

# _pf_disk_grade DIR WHAT [REUSED_KB] [FREED] -- one disk line: the free space on DIR,
# which will hold WHAT, graded against the Linux floors. REUSED_KB, the images a re-run
# of this installer's k3s already holds on DIR's disk, counts as free, and the line says
# so. FREED is what a consented move off k3d frees on DIR's disk before step b
# (_pf_k3d_freed_on): KB, counted as free and named; "unknown", named and not counted;
# "none" (the default), no move.
_pf_disk_grade() {
  local at="$1" what="$2" reused="${3:-0}" freed="${4:-none}" free_kb free_gb rq ru=GB
  free_kb="$(_pf_free_kb "$at")"
  if [[ -z "$free_kb" ]]; then warn "Disk: couldn't determine free space on ${at} for ${what} (skipping)."; return 0; fi
  if [[ "$reused" -gt 0 ]]; then
    free_kb=$(( free_kb + reused ))
    rq=$(( reused / 1024 / 1024 )); [[ "$rq" -gt 0 ]] || { rq=$(( reused / 1024 )); ru=MB; }
    what="${what}, counting the ${rq} ${ru} of images this k3s already holds, which the re-run reuses"
  fi
  if [[ "$freed" == 0 ]]; then
    what="${what}; the move off k3d frees nothing on this disk (cluster '${TRACEBLOC_REINSTALL_CLUSTER:-}' keeps its volumes on another)"
  elif [[ "$freed" =~ ^[0-9]+$ ]]; then
    free_kb=$(( free_kb + freed ))
    ru=GB; rq=$(( freed / 1024 / 1024 )); [[ "$rq" -gt 0 ]] || { rq=$(( freed / 1024 )); ru=MB; }
    what="${what}, counting the ${rq} ${ru} the move off k3d frees on this disk (cluster '${TRACEBLOC_REINSTALL_CLUSTER:-}' and its volumes)"
  elif [[ "$freed" == "unknown" ]]; then
    what="${what}, not counting what the move off k3d frees, which could not be measured"
  fi
  free_gb=$(( free_kb / 1024 / 1024 ))
  if [[ "$free_gb" -lt "$PF_MIN_DISK_GB" ]]; then
    _pf_fail_line "Disk: only ${free_gb} GB free on ${at} for ${what} — need ≥ ${PF_MIN_DISK_GB} GB."
    PF_HARD_FAIL=$(( ${PF_HARD_FAIL:-0} + 1 ))
    hint "Free up space or attach a larger disk, then re-run."
  elif [[ "$free_gb" -lt "$PF_WARN_DISK_GB" ]]; then
    warn "Disk: ${free_gb} GB free on ${at} for ${what} — recommended ≥ ${PF_WARN_DISK_GB} GB; images + data may fill it."
  else
    _pf_ok "Disk: ${free_gb} GB free on ${at} for ${what}"
  fi
  return 0
}

# The network-filesystem classification shared by the full storage check and
# the pre-log early_data_dir_guard (#432). Everything listed corrupts or
# crash-loops MySQL/InnoDB (broken POSIX locking, unsafe O_DIRECT/fsync).
#
# The name is NORMALISED before matching, so the list carries BARE names only and
# a FUSE filesystem can never fall through it for want of a spelling. A FUSE mount
# reaches us spelled either way, depending on which reader in _pf_fstype answered:
# findmnt and mount(8) report the libfuse SUBTYPE (`fuse.sshfs`), so the list used
# to carry `fuse.`-prefixed entries — but half of them had no bare twin, which is
# the shape that regrows this bug. Strip the prefix once instead of extending the
# list twice. (Measured on Ubuntu 24.04 / libfuse 3.14 / util-linux 2.39 and
# Ubuntu 20.04 / libfuse 2.9: sshfs and rclone both mount as `fuse.<subtype>`.)
_pf_is_network_fstype() {
  local t
  t="$(printf '%s' "${1:-}" | tr '[:upper:]' '[:lower:]')"
  t="${t#fuse.}"                       # fuse.sshfs -> sshfs; nfs4 -> nfs4
  case "$t" in
    nfs|nfs3|nfs4|nfsd|cifs|smb|smbfs|smb2|smb3|afpfs|9p|ncpfs|gfs|gfs2|ocfs2|lustre|glusterfs|ceph|beegfs|sshfs|s3fs|gcsfuse|blobfuse|blobfuse2|davfs|webdav|rclone) return 0 ;;
    # AN UNRECOGNISED FUSE SUBTYPE IS NOT EVIDENCE OF LOCAL STORAGE (saadqbal,
    # #726). `fuse.gcsfuse` and `fuse.blobfuse2` are named above now, but the
    # list can only ever hold the drivers someone thought of -- and the next
    # cloud FUSE ships without asking us. Before this, `fuse.<anything else>`
    # stripped to a name nobody matched and fell through to a confident
    # "Local storage", which is the failure mode this predicate exists to
    # prevent, one subtype at a time.
    #
    # Returning 1 ("not network") is still right -- we have no evidence it IS
    # network, and a hard fail on a local ntfs-3g would be worse. The caller
    # asks `_pf_is_opaque_fuse_fstype` next, which now claims this shape and
    # warns, so an unknown FUSE reads as unknown rather than as local.
    *) return 1 ;;
  esac
}

# FUSE with the subtype ERASED: the mount table says "this is FUSE" without saying
# WHICH FUSE, so sshfs/s3fs/rclone (fatal for the database) is indistinguishable
# from a local ntfs-3g/gocryptfs/bindfs (fine). This is not an edge case — two of
# _pf_fstype's three readers produce ONLY this shape, so _pf_is_network_fstype above
# never sees a name it can classify:
#   * `stat -f -c %T` — the Linux fallback when findmnt is missing — answers
#     `fuseblk` for EVERY fuse mount (the fuse and fuseblk kernel filesystems share
#     one magic number). Measured: sshfs, rclone AND bindfs all read back `fuseblk`.
#   * macOS has no findmnt and skips the stat reader (BSD `stat -f` is a format
#     string), so the df+mount path answers with the macFUSE vfs name — `macfuse`,
#     or `osxfuse` before 4.x — never a `fuse.*` subtype.
#   * A FUSE program that sets no subtype mounts as bare `fuse` even under findmnt
#     (measured with bindfs; libfuse only defaults the subtype to the program name).
# Callers WARN rather than refuse: refusing every unnamed FUSE mount would block a
# legitimate local one, and TRACEBLOC_ALLOW_NETWORK_FS reads as nonsense advice to
# someone who is not on a network filesystem.
_pf_is_opaque_fuse_fstype() {
  local t
  t="$(printf '%s' "${1:-}" | tr '[:upper:]' '[:lower:]')"
  case "$t" in
    fuse|fuseblk|macfuse|osxfuse|osxfusefs) return 0 ;;
    # A NAMED SUBTYPE WE DO NOT KNOW (saadqbal, #726). `fuse.gcsfuse` used to
    # be neither network (not on the list) nor opaque (not bare `fuse`), so it
    # reached the `else` and was announced as "Local storage" -- a confident
    # answer about a mount we could not identify.
    #
    # THE TWO PREDICATES STAY MUTUALLY EXCLUSIVE, which the bats suite asserts
    # and which is worth more than it looks: without the negation below,
    # `fuse.sshfs` would satisfy BOTH, and the only thing keeping it a hard
    # fail rather than a warning would be the order the caller happens to ask
    # in. A future caller asking "opaque?" first would silently downgrade a
    # database-corrupting mount to a notice. Excluding the names the network
    # classifier claims makes the correct answer independent of call order.
    fuse.*) _pf_is_network_fstype "$t" && return 1; return 0 ;;
    *) return 1 ;;
  esac
}

# The shared advisory for an opaque FUSE mount (see above): say what we can and
# cannot tell, and let the install continue. $1 = path, $2 = fstype as read.
_pf_opaque_fuse_warn() {
  # TWO DIFFERENT UNKNOWNS, AND SAYING THE WRONG ONE IS A FALSE STATEMENT
  # (saadqbal, #726). The original line — "the mount table doesn't say which
  # one" — is true for `fuse`/`fuseblk`, where the subtype really is erased. It
  # would be a lie for `fuse.gocryptfs`, where the table says exactly which one
  # and the gap is that WE have no opinion on it. Same advice, honest premise.
  case "$(printf '%s' "${2:-}" | tr '[:upper:]' '[:lower:]')" in
    fuse.*) warn "Storage: ${1} is on a FUSE filesystem (${2}) — a driver this check does not recognise." ;;
    *)      warn "Storage: ${1} is on a FUSE filesystem (${2}) — the mount table doesn't say which one." ;;
  esac
  hint "If it is network-backed (sshfs, s3fs, rclone, a cloud-sync mount), the client database (MySQL/InnoDB) can corrupt or crash-loop — move HOST_DATA_DIR to a local disk under your \$HOME."
  hint "If it is a local FUSE mount (ntfs-3g, gocryptfs, bindfs), this is only a notice — the install continues."
}

# The FOLLOWABLE remedy for a network-filesystem HOST_DATA_DIR (#479). validate_config
# requires the data dir UNDER $HOME (security, Bugbot #384), so "set HOST_DATA_DIR to
# ~/.tracebloc" is un-followable on a network HOME — that path is still NFS. Name the
# options that actually work. Shared by _pf_storage_type and early_data_dir_guard so
# the two remedies can never drift (early_data_dir_guard already had the good text).
_pf_network_fs_remedy() {
  hint "HOST_DATA_DIR must be a LOCAL disk under your \$HOME (paths outside \$HOME are rejected), so on a network home either:"
  hint "  1. install as a user whose home is on a local disk (ask your admin), or"
  hint "  2. set TRACEBLOC_ALLOW_NETWORK_FS=1 to proceed anyway - NOT recommended: the database can corrupt."
  hint "(Datasets may stay on network storage via HOST_DATASET_DIR - only the data dir must be local.)"
}

# Pre-log guard (#432): main() creates HOST_DATA_DIR and tees the session log
# onto it (setup_log_file) BEFORE run_preflight fires — on an NFS home under
# sudo + root_squash that unguarded mkdir fails with a bare error (or the log
# dir lands squashed/nobody-owned) before _pf_storage_type below can print its
# friendly, named failure. Same classification, run first, output only on
# failure. TRACEBLOC_ALLOW_NETWORK_FS defers to the full check's warning.
#
# Native k3s under node-local judges the directory _pf_storage_type judges, the
# storage path, where its database lives (under hostpath, HOST_DATA_DIR): an NFS home with k3s's default storage holds only logs and
# config, so it passes here as it passes there. When reading the storage path
# needs a password (or cannot answer), this pre-log guard defers to the full check,
# which asks and refuses by name. What k3s gives up: a root login whose own home is
# on a root_squash NFS gets mkdir's bare error instead of this one (a sudo-wrapped
# run is refused before this point, refuse_sudo_wrapped_install).
early_data_dir_guard() {
  local target fstype
  target="${HOST_DATA_DIR:-${HOME:-}/.tracebloc}"
  [[ -n "${TRACEBLOC_ALLOW_NETWORK_FS:-}" ]] && return 0
  # hostpath keeps the database under HOST_DATA_DIR on native k3s too (client-dev#1782).
  # The macOS node keeps its data in its own volume, so the directory created here is
  # HOST_DATA_DIR, as on k3d (_pf_storage_type checks where the volume lives).
  if [[ "${TRACEBLOC_SUBSTRATE_RESOLVED:-}" == "k3s" && "${TB_STORAGE_MODE:-node-local}" == "node-local" ]] && ! _pf_on_mac_node; then
    target="$(_native_k3s_storage_path)" || return 0
  fi
  # An EXISTING data dir has no at-risk mkdir here, and a healthy machine's
  # re-run must keep reaching the assess hand-off exactly as it did when this
  # check lived only in run_preflight (Bugbot #441). The full preflight guard
  # below still classifies network storage for actual (re)installs.
  [[ -d "$target" ]] && return 0
  fstype="$(_pf_fstype "$target")"
  [[ -z "$fstype" ]] && return 0                 # undetermined — assume local
  if ! _pf_is_network_fstype "$fstype"; then
    # Opaque FUSE (`fuseblk`, `macfuse`): we cannot name it, so we must not refuse
    # — but staying silent is what let an sshfs data dir through on every reader
    # that erases the subtype. Say so and continue; the full check repeats it once
    # logging is up. (Explicit `if`, not `a && b`: under set -e a false `&&` chain
    # here would decide the function's exit status.)
    if _pf_is_opaque_fuse_fstype "$fstype"; then _pf_opaque_fuse_warn "$target" "$fstype"; fi
    return 0
  fi
  warn "Storage: ${target} is on a network filesystem (${fstype})."
  hint "The client database (MySQL/InnoDB) corrupts or crash-loops on network storage, and NFS root_squash blocks data-dir setup."
  _pf_network_fs_remedy   # shared followable remedy (#479)
  error "Refusing to create the data directory on ${fstype} before logging starts."
}

# Network-filesystem guard for HOST_DATA_DIR. MySQL/InnoDB corrupts or crash-loops
# on NFS/CIFS/SMB (broken POSIX locking + unsafe O_DIRECT/fsync), and the chart's
# root chown init-container is blocked by NFS root_squash — so a network data dir
# fails ~20 min in with a cryptic CrashLoopBackOff. Catch it in seconds here.
_pf_storage_type() {
  local target fstype disp tab=$'\t'
  target="${HOST_DATA_DIR:-$HOME/.tracebloc}"
  # Native k3s keeps the database in a local-path volume, under the storage path, so
  # that is the directory that must be local. _pf_disk_k3s has already read it (and
  # refused when it could not: PF_HARD_FAIL is raised and run_preflight stops), so a
  # failure here adds nothing (preflight.bats pins it). Under hostpath the database
  # is the chart's hostPath PV under HOST_DATA_DIR
  # (client-dev#1782), so HOST_DATA_DIR is the directory judged -- on native k3s an
  # installed release's own root (_hostpath_root).
  # The macOS node keeps it in the node's volume, a sparse image under the runtime's app
  # root, so that directory must be local: measured where the disk line measures it, and
  # when that cannot be told the disk line has already said so. Under hostpath it is in
  # the hostPath folder on this Mac, which the node mounts, judged as on native k3s.
  if _pf_on_mac_node && [[ "${TB_STORAGE_MODE:-node-local}" != "hostpath" ]]; then
    target="$(_pf_mac_node_disk_at)" || return 0
    target="${target%%"$tab"*}"
  elif [[ "${TRACEBLOC_SUBSTRATE_RESOLVED:-}" == "k3s" && "${TB_STORAGE_MODE:-node-local}" == "node-local" ]]; then
    target="$(_native_k3s_storage_path)" || return 0
  elif [[ "${TRACEBLOC_SUBSTRATE_RESOLVED:-}" == "k3s" && -n "$(_hostpath_root)" ]]; then
    target="$(_hostpath_root)"
  fi
  disp="$target"
  if [[ -n "${HOME:-}" && "$disp" == "$HOME"* ]]; then disp="~${disp#"$HOME"}"; fi
  fstype="$(_pf_fstype "$target")"
  if [[ -z "$fstype" ]]; then
    log "Storage: ${target} — filesystem type undetermined; assuming local."
    success "Local storage (${disp})"
    return 0
  fi
  if _pf_is_network_fstype "$fstype"; then
      if [[ -n "${TRACEBLOC_ALLOW_NETWORK_FS:-}" ]]; then
        warn "Storage: ${target} is on a network filesystem (${fstype}) — proceeding (TRACEBLOC_ALLOW_NETWORK_FS set); the client database may corrupt or crash-loop on network storage."
        return 0
      fi
      _pf_fail_line "Storage: ${target} is on a network filesystem (${fstype}) — the tracebloc client database (MySQL/InnoDB) corrupts or crash-loops on network storage, and NFS root_squash blocks data-dir setup."
      PF_HARD_FAIL=$(( ${PF_HARD_FAIL:-0} + 1 ))
      # The old remedy suggested HOST_DATA_DIR=$HOME/.tracebloc — but on a network HOME
      # that's still NFS, and validate_config rejects paths OUTSIDE $HOME, so it could
      # never work. Use the shared followable remedy (#479).
      _pf_network_fs_remedy
  elif _pf_is_opaque_fuse_fstype "$fstype"; then
      # FUSE, subtype unknown — advisory, never a hard fail (see the predicate).
      log "Storage: ${target} (${fstype})"
      _pf_opaque_fuse_warn "$target" "$fstype"
  else
      log "Storage: ${target} (${fstype})"
      success "Local storage (${disp})"
  fi
  # backend#743: datasets MAY live on a network mount (HOST_DATASET_DIR) — only
  # the database dir (HOST_DATA_DIR, checked above) must be local. Note it, never fail.
  if [[ -n "${HOST_DATASET_DIR:-}" ]]; then
    local dfstype; dfstype="$(_pf_fstype "$HOST_DATASET_DIR")"
    info "Dataset dir: ${HOST_DATASET_DIR}${dfstype:+ (${dfstype})} — network mounts are supported here (the database stays on local disk)."
  fi
  return 0
}

# ── Network profile (#582) ───────────────────────────────────────────────────
# A plain-language read of the network BEFORE the endpoint probes, so a user on a
# restricted/corporate network sees what's happening up front instead of a cryptic
# failure minutes in. Detects an explicit proxy, a configured corporate CA bundle,
# and (best-effort) TLS inspection. Never fatal, bounded, PII-free (proxy
# credentials are stripped and never printed/logged). The connectivity probes and
# the break-and-inspect hint below still own the actionable fix guidance.

# Strip scheme:// and any user:pass@ credentials from a proxy URL; echo bare
# host:port. Credentials must NEVER reach the screen or log (#576).
_pf_proxy_hostport() {
  local u="${1:-}"
  u="${u#*://}"     # drop scheme://
  u="${u#*@}"       # drop user:pass@ credentials (PII)
  u="${u%%/*}"      # drop any /path
  echo "$u"
}

# Echo the first explicit proxy from the environment as a bare host:port (creds
# stripped), or empty when none is set. HTTPS takes precedence (that's the one that
# matters for our all-HTTPS egress).
_pf_env_proxy() {
  local v val
  for v in HTTPS_PROXY https_proxy HTTP_PROXY http_proxy; do
    val="${!v:-}"; [[ -n "$val" ]] && { _pf_proxy_hostport "$val"; return 0; }
  done
  return 0
}

# Echo the first explicit proxy from the environment VERBATIM (scheme + any
# user:pass credentials intact), or empty. For the probe CONNECTION only — an
# authenticated proxy needs the credentials to answer the CONNECT, or it 407s and
# the inspection probe silently returns 'unknown' (Bugbot). NEVER print/log this;
# display always uses the credential-stripped _pf_env_proxy.
_pf_env_proxy_raw() {
  local v val
  for v in HTTPS_PROXY https_proxy HTTP_PROXY http_proxy; do
    val="${!v:-}"; [[ -n "$val" ]] && { printf '%s' "$val"; return 0; }
  done
  return 0
}

# Percent-decode a URL-encoded string (proxy userinfo), as .NET's
# [Uri]::UnescapeDataString does, so an encoded credential (e.g. a "%40" in a
# password) authenticates as the user wrote it (Bugbot). Percent-only: userinfo
# does not use '+'-for-space, so '+' is left literal.
_pf_urldecode() {
  local s="${1:-}"
  # Escape literal backslashes first so printf '%b' expands ONLY the percent-escapes
  # we turn into \xHH below -- otherwise a '\' (or a '\n'/'\t') in the password is
  # taken as an escape, diverging from .NET's percent-only UnescapeDataString
  # (Bugbot, client#589).
  s="${s//\\/\\\\}"
  printf '%b' "${s//%/\\x}"
}

# Echo the configured corporate CA bundle path when TRACEBLOC_CA_BUNDLE or
# CURL_CA_BUNDLE points at a readable file; empty otherwise. SOFT (never errors) —
# the hard validation lives in cluster.sh's _resolve_ca_bundle at cluster-create.
_pf_env_ca_bundle() {
  local v val
  for v in TRACEBLOC_CA_BUNDLE CURL_CA_BUNDLE; do
    val="${!v:-}"; [[ -n "$val" && -f "$val" && -r "$val" ]] && { echo "$val"; return 0; }
  done
  return 0
}

# Return 0 if an X.509 issuer string names a well-known PUBLIC CA (a normal direct
# chain); 1 otherwise (a corporate re-signer — i.e. TLS inspection). Pure/testable.
_pf_issuer_is_public() {
  # Here-string, not a pipe into grep -q (backend#1778): -q closes on the first
  # match, and under inherited pipefail that makes the pipeline 141 even on a
  # MATCH -- inverting this predicate's answer for a long issuer string.
  grep -qiE "DigiCert|Sectigo|Comodo|Let'?s Encrypt|ISRG|Google Trust|GTS |GlobalSign|Amazon|Entrust|GeoTrust|Baltimore|USERTrust|Actalis|Buypass|SSL\.com|Certum|IdenTrust|Microsoft (Azure|RSA|ECC)" <<<"${1:-}"
}

# Best-effort affirmative TLS-inspection probe. Echo yes|no|unknown. Reads the
# issuer of the cert served for a well-known public host (through the proxy when
# one is set); a non-public issuer means a corporate CA is re-signing TLS. Bounded
# and non-hanging: needs openssl AND a timeout tool, else 'unknown' (we never run
# an unbounded openssl s_client that a blackholed 443 could hang forever).
_pf_detect_tls_inspection() {
  has openssl || { echo "unknown"; return 0; }
  { has timeout || has gtimeout; } || { echo "unknown"; return 0; }
  local host="github.com" raw issuer creds user="" pass=""
  local -a args=(s_client -connect "${host}:443" -servername "$host")
  # Connect THROUGH the proxy using the raw value: -proxy takes host:port (creds
  # stripped), and an authenticated proxy additionally needs -proxy_user/-proxy_pass
  # (openssl >= 3.0) or it 407s and issuer capture fails → a false 'unknown' on the
  # exact TLS-inspecting networks this exists to detect (Bugbot). Credentials go to
  # openssl only, URL-decoded (_pf_urldecode) and NEVER printed/logged.
  raw="$(_pf_env_proxy_raw)"
  if [[ -n "$raw" ]]; then
    args+=(-proxy "$(_pf_proxy_hostport "$raw")")
    # Capture-then-match, not `openssl -help | grep -q`: under pipefail, grep -q closing
    # the pipe early makes openssl take SIGPIPE and the pipeline fail, dropping the
    # credential flags on exactly the authenticated proxies this handles (Bugbot, client#589).
    if [[ "$raw" == *"@"* ]] && { _pf_ossl_help="$(openssl s_client -help 2>&1 || true)"; [[ "$_pf_ossl_help" == *"-proxy_user"* ]]; }; then
      creds="${raw#*://}"; creds="${creds%%@*}"          # user[:pass], percent-encoded
      if [[ "$creds" == *:* ]]; then
        user="$(_pf_urldecode "${creds%%:*}")"; pass="$(_pf_urldecode "${creds#*:}")"
      else
        user="$(_pf_urldecode "$creds")"; pass=""        # user@ with no password
      fi
      # Pass the password via env: (openssl reads $_TB_PROXY_PASS) so it never lands
      # in argv / ps / /proc/*/cmdline on a shared host (Bugbot). Username isn't secret.
      args+=(-proxy_user "$user" -proxy_pass "env:_TB_PROXY_PASS")
    fi
  fi
  # echo | : send EOF so s_client returns after the handshake. We deliberately do
  # NOT pass -verify_return_error — we want the served cert's issuer even when the
  # corporate CA isn't trusted, so we can name the inspection. The password is
  # exported ONLY inside this command-substitution subshell (openssl reads it via
  # env:), so it never reaches argv or the parent shell. `|| issuer=""` keeps a
  # failed/timed-out probe from aborting under `set -euo pipefail` (like _pf_probe_url).
  issuer="$(
    export _TB_PROXY_PASS="$pass"
    echo | _bounded 8 openssl "${args[@]}" 2>/dev/null | openssl x509 -noout -issuer 2>/dev/null  # set-u-safe: seeded with the s_client verb
  )" || true   # keep a captured issuer: s_client often exits non-zero (SIGPIPE after
                # x509 finishes) even on a good handshake; a genuinely empty capture is
                # still caught by the [[ -z ]] below (Bugbot High, client#589).
  [[ -z "$issuer" ]] && { echo "unknown"; return 0; }
  if _pf_issuer_is_public "$issuer"; then echo "no"; else echo "yes"; fi
}

# Print the plain-language network profile line (only when noteworthy — a plain
# direct connection stays silent; the "Connected:" line already confirms egress).
# Exports PF_NET_PROXY / PF_NET_CA / PF_NET_INSPECT for later reuse.
_pf_network_profile() {
  PF_NET_PROXY="$(_pf_env_proxy)"
  PF_NET_CA="$(_pf_env_ca_bundle)"
  PF_NET_INSPECT="$(_pf_detect_tls_inspection)"

  # Nothing noteworthy: no proxy and inspection not affirmatively detected.
  [[ -z "$PF_NET_PROXY" && "$PF_NET_INSPECT" != "yes" ]] && return 0

  local -a parts=()
  [[ -n "$PF_NET_PROXY" ]]            && parts+=("corporate proxy detected (${PF_NET_PROXY})")
  [[ "$PF_NET_INSPECT" == "yes" ]]    && parts+=("TLS inspection detected")
  [[ -n "$PF_NET_CA" ]]               && parts+=("your company's certificate is configured")
  local joined="" p
  for p in "${parts[@]}"; do joined="${joined:+$joined; }$p"; done  # set-u-safe: past the early return, a proxy or TLS inspection adds a part
  info "Network: ${joined}."
  return 0
}

# True on a host where k3s's install.sh installs the k3s-selinux policy from
# rpm.rancher.io: /usr/share/selinux is a directory, and the host is one its
# install_selinux_rpm serves -- an rpm release file, or ID_LIKE starting with
# suse (read from install.sh at v1.36.3+k3s1: setup_selinux, install_selinux_rpm).
# The api.github.com version lookup beside it times out to a default, so it is not
# a host the install needs. ROOT (default /) is the tests' seam.
_pf_k3s_selinux_rpm_host() {
  local root="${1:-}" f id_like=""
  [[ -d "${root}/usr/share/selinux" ]] || return 1
  for f in redhat-release centos-release oracle-release fedora-release system-release; do
    [[ -r "${root}/etc/${f}" ]] && return 0
  done
  if [[ -r "${root}/etc/os-release" ]]; then
    id_like="$(sed -n 's/^ID_LIKE=//p' "${root}/etc/os-release")"
    id_like="${id_like%%$'\n'*}"; id_like="${id_like#\"}"; id_like="${id_like%\"}"
    [[ "${id_like%% *}" == "suse" ]] && return 0
  fi
  return 1
}

_pf_connectivity() {
  _pf_network_profile   # #582: announce the network profile before the probes
  # Can't probe without curl — and on the direct ./install-k8s.sh path the
  # installer hasn't installed it yet. Skip with a warning rather than hard-fail
  # with a misleading "egress blocked" (curl is installed downstream).
  if ! has curl; then
    warn "Skipping connectivity check — curl isn't available yet (the installer will add it)."  # style-guard: allow (copy, not a call)
    return 0
  fi
  local backend_host cfail=0 tls_seen=0 c label rest url mode status
  backend_host="$(_pf_backend_host)"

  # Critical: the install cannot succeed without these (image pulls, creds, chart).
  # Entries are "label|url" with an optional third "|strict" field.
  local criticals=(
    "Docker Hub (registry-1.docker.io)|https://registry-1.docker.io/v2/"
    # auth.docker.io is Docker Hub's token endpoint: a network that allows
    # registry-1 but blocks the token host fails only at in-cluster pull time (#416).
    "Docker Hub auth (auth.docker.io)|https://auth.docker.io/token"
    "GitHub Container Registry (ghcr.io)|https://ghcr.io/"
    "tracebloc API (${backend_host})|https://${backend_host}/"
    # The chart repo is probed at its index.yaml, strictly (third field): the site
    # ROOT 404s by design, while the index must exist for `helm repo add` (#385).
    "tracebloc Helm charts (tracebloc.github.io)|https://tracebloc.github.io/client/index.yaml|strict"
  )
  # Tool-binary download hosts — promoted to HARD (#416): a blocked one used to
  # pass preflight then fail the install ~30s later. Only added when the fetch will
  # actually happen (tool absent; a present tool is never re-downloaded). These are
  # UNAMBIGUOUS: the installer always fetches kubectl/k3d/helm from exactly these
  # hosts. Release assets 302 to objects.githubusercontent.com and _pf_probe_url
  # does not follow redirects, so github.com passing proves nothing about the asset
  # host — probe it explicitly. check-drift.sh holds the probe list to these hosts.
  #
  # The Docker-ENGINE install host is deliberately NOT hard: it's path/distro/
  # environment-dependent (Debian→get.docker.com, RHEL clones→download.docker.com,
  # Amazon/Arch/SUSE→distro repos). preflight can't cheaply know which, so hard-probing a fixed host
  # would abort supported paths that never touch it (Bugbot). It goes in `soft`
  # (warn-only) below. Windows runs this core inside tracebloc's WSL distro, on
  # native k3s, so it fetches no Docker engine at all.
  local soft=() tool_hosts="dl.k8s.io / get.helm.sh / github.com / objects.githubusercontent.com" nodes_trust="The k3d nodes are"
  if _pf_on_mac_node; then
    # A Mac sets up only the macOS node (slim client 4.1). Apple's runtime
    # package comes from its GitHub release, whose download redirects to
    # release-assets.githubusercontent.com (keyed on the runtime's folder, which a
    # re-run reuses); kubectl, pinned to the node's release, from dl.k8s.io; helm from
    # get.helm.sh when absent. The kernel and init image (ghcr.io) and the node image
    # (Docker Hub) are in the always-needed set above.
    if [[ ! -e "$(_mac_ct_install_root 2>/dev/null)" ]]; then
      criticals+=("Apple container package (github.com)|https://github.com/" \
                  "Apple container assets (release-assets.githubusercontent.com)|https://release-assets.githubusercontent.com/")
    fi
    criticals+=("kubectl (dl.k8s.io)|https://dl.k8s.io/")
    if ! has helm; then criticals+=("Helm (get.helm.sh)|https://get.helm.sh/"); fi
    tool_hosts="github.com / release-assets.githubusercontent.com / dl.k8s.io / get.helm.sh"
    # The node takes the CA's roots by path (mac-container.sh's _mac_ct_node_ca).
    nodes_trust="The macOS node is"
  elif [[ "${TRACEBLOC_SUBSTRATE_RESOLVED:-}" == "k3s" ]]; then
    # NATIVE k3s fetches no k3d, no kubectl (k3s carries its own) and no Docker, so
    # none of their hosts is probed. Its hosts are keyed on what THIS run fetches,
    # never on k3s merely being there, so a re-run that needs a host is checked for
    # it before anything changes (client-dev#1994):
    #   - the binary, from github.com, whose release download redirects to
    #     release-assets.githubusercontent.com (measured on v1.36.3+k3s1 under 1.1b):
    #     on the predicate step c downloads on, a k3s that is absent or not the pin;
    #   - nothing from raw.githubusercontent.com: k3s's install.sh ships with the
    #     installer (scripts/vendor/);
    #   - rpm.rancher.io on EVERY run of an SELinux rpm host: install.sh runs on every
    #     pass and installs or refreshes k3s-selinux from there each time, and with
    #     the host blocked a re-run fails at its `dnf install` (measured on Rocky 9).
    #     Its api.github.com version lookup is not probed: install.sh only warns
    #     when it fails (measured too).
    if _native_k3s_binary_due; then
      criticals+=("k3s download (github.com)|https://github.com/" \
                  "k3s assets (release-assets.githubusercontent.com)|https://release-assets.githubusercontent.com/")
    fi
    # On an SELinux-enforcing host a missing policy is fatal to install.sh.
    if _pf_k3s_selinux_rpm_host; then
      criticals+=("k3s SELinux policy (rpm.rancher.io)|https://rpm.rancher.io/")
    fi
    if ! has helm;    then criticals+=("Helm (get.helm.sh)|https://get.helm.sh/"); fi
    tool_hosts="github.com / release-assets.githubusercontent.com / get.helm.sh / rpm.rancher.io"
    nodes_trust="k3s is"
  elif [[ "$OS" == "Linux" ]]; then
    if ! has k3d;     then criticals+=("k3d download (github.com)|https://github.com/" \
                                       "k3d assets (objects.githubusercontent.com)|https://objects.githubusercontent.com/"); fi
    if ! has kubectl; then criticals+=("kubectl (dl.k8s.io)|https://dl.k8s.io/"); fi
    if ! has helm;    then criticals+=("Helm (get.helm.sh)|https://get.helm.sh/"); fi
    if ! has docker;  then soft+=("Docker install (get.docker.com)|https://get.docker.com/" \
                                  "Docker packages (download.docker.com)|https://download.docker.com/"); fi
  fi
  # Probe each critical host in the FOREGROUND (so PF_HARD_FAIL updates in THIS
  # shell — a backgrounded spinner subshell couldn't propagate it), advancing a
  # spinner frame before each blocking probe. No sleep: the network probe itself
  # is the delay in production; under test the stubbed probe is instant, so this
  # can never hang. Failures are collected and printed after the line is cleared.
  local frames=('⠋' '⠙' '⠹' '⠸' '⠼' '⠴' '⠦' '⠧' '⠇' '⠏') fi=0
  local -a fails=()
  _tb_progress_start "Checking outbound connectivity…"
  for c in "${criticals[@]}"; do  # set-u-safe: criticals is a literal list
    label="${c%%|*}"; rest="${c#*|}"; url="${rest%%|*}"
    mode=""; [[ "$rest" == *"|"* ]] && mode="${rest##*|}"
    _tb_progress_frame "${frames[fi]}" "Checking outbound connectivity…"
    fi=$(( (fi + 1) % ${#frames[@]} ))
    status="$(_pf_probe_url "$url" "$mode")"
    if [[ "$status" != "ok" ]]; then status="$(_pf_probe_url "$url" "$mode")"; fi   # one retry (transient blips)
    if [[ "$status" != "ok" ]]; then
      fails+=("${label}|${status}")
      if [[ "$status" == "tls" ]]; then tls_seen=1; fi
    fi
  done
  _tb_progress_end

  if [[ ${#fails[@]} -eq 0 ]]; then
    # Collapsed happy-path line (always shown — this IS the connectivity result,
    # not one of the arch/CPU/RAM/disk lines the summary folds together).
    success "Connected: tracebloc.io, Docker Hub (registry-1.docker.io), GitHub (ghcr.io)"
  else
    local ff
    for ff in "${fails[@]}"; do  # set-u-safe: the else of the empty-fails check
      _pf_fail_line "${ff%%|*} unreachable (${ff#*|})"
      PF_HARD_FAIL=$(( ${PF_HARD_FAIL:-0} + 1 ))
      cfail=$(( cfail + 1 ))
    done
  fi

  # Path-dependent Docker-engine hosts: WARN only (never hard) so a blocked host on
  # a path that won't use it doesn't abort a supported install (Bugbot). The
  # ${soft[@]+…} guard keeps `set -u` happy with an empty array on bash 3.2 (macOS).
  for c in ${soft[@]+"${soft[@]}"}; do
    label="${c%%|*}"; url="${c#*|}"
    status="$(_pf_probe_url "$url")"
    [[ "$status" == "ok" ]] || warn "${label} unreachable (${status}) — only needed if the installer fetches Docker from that host; other install paths don't."
  done

  if [[ "$tls_seen" -eq 1 ]]; then
    hint "A TLS/certificate error usually means a break-and-inspect (TLS-inspecting) proxy whose corporate CA isn't trusted here."
    hint "Fix THESE host checks with CURL_CA_BUNDLE=/path/to/corporate-ca.pem (the installer's HTTPS downloads honor it) or by adding the CA to the system trust store. ${nodes_trust} trusted separately via TRACEBLOC_CA_BUNDLE (or CURL_CA_BUNDLE) at cluster-create — so CURL_CA_BUNDLE covers both, TRACEBLOC_CA_BUNDLE only the nodes. Ask IT for the bundle if unsure."
  fi
  if [[ "$cfail" -gt 0 ]]; then
    hint "Allow HTTPS (443) egress to the host(s) named above — the always-needed set is registry-1.docker.io, auth.docker.io, ghcr.io, ${backend_host}, tracebloc.github.io, plus any tool-download host listed (${tool_hosts}) — or set HTTP_PROXY if you use a corporate proxy."
  fi
  # #585: when the CONTAINER REGISTRIES themselves are blocked (not just any host),
  # the images can't be pulled directly at all — surface the mirror / offline options
  # in plain language instead of leaving the generic egress hint as the only guidance.
  local ff reg_blocked=0
  for ff in ${fails[@]+"${fails[@]}"}; do
    case "${ff%%|*}" in
      *registry-1.docker.io*|*auth.docker.io*|*ghcr.io*) reg_blocked=1 ;;
    esac
  done
  if [[ "$reg_blocked" -eq 1 ]]; then
    hint "The container registries (Docker Hub / GHCR) look blocked here, so the images can't be pulled directly. If your site runs a mirror you CAN reach, point the install at it; for a fully offline site, an air-gapped image bundle is the alternative. See the 'Blocked container registry' section of docs/INSTALL.md."
  fi
  return 0
}

# One-line hardware summary for the collapsed step-a view:
#   "arch · N CPU cores · N GB memory · N GB free disk"
# Computed from the same readers the individual checks use, so it can never
# disagree with them. Fields that can't be read are simply omitted (arch always
# leads). Printed by run_preflight only when nothing hard-failed — a ✔ summary
# above a ✖ would contradict itself.
_pf_hw_summary_line() {
  local cpu mem_kb mem_gb disk_target="" disk_kb disk_gb tab=$'\t'
  local -a parts=("$ARCH")
  cpu="$(_pf_ncpu)"
  if [[ -n "$cpu" ]]; then parts+=("${cpu} CPU cores"); fi
  # Host RAM, not the VM budget (#417): a hardware summary that read "7 GB
  # memory" on a 15 GB machine (a VM's default budget) was the same
  # flip-flop bug in miniature. Fall back to the runtime only if the host is
  # unreadable, so the field is still populated rather than dropped.
  mem_kb="$(_pf_host_mem_kb)"; [[ -z "$mem_kb" ]] && mem_kb="$(_pf_runtime_mem_kb)"
  # Through the shared converter so the collapsed summary can never disagree with
  # the memory line above it (Bugbot #445 r6).
  if [[ -n "$mem_kb" ]]; then mem_gb="$(_pf_display_gb_from_mib "$(( mem_kb / 1024 ))")"; parts+=("${mem_gb} GB memory"); fi
  if _pf_on_mac_node; then
    # The node's app root, measured where _pf_disk_mac_node measures it; none when
    # that cannot be told, so the field is dropped rather than guessed.
    disk_target="$(_pf_mac_node_disk_at)" && disk_target="${disk_target%%"$tab"*}" || disk_target=""
  elif [[ "${TRACEBLOC_SUBSTRATE_RESOLVED:-}" == "k3s" ]]; then
    # k3s's data path, measured where _pf_disk_k3s measures it.
    disk_target="$(_pf_nearest_existing "$TB_K3S_DATA_PATH")"; [[ -n "$disk_target" ]] || disk_target="/"
  fi
  disk_kb=""; [[ -z "$disk_target" ]] || disk_kb="$(_pf_free_kb "$disk_target")"
  if [[ -n "$disk_kb" ]]; then disk_gb=$(( disk_kb / 1024 / 1024 )); parts+=("${disk_gb} GB free disk"); fi
  local joined="" p
  for p in "${parts[@]}"; do joined="${joined:+$joined · }$p"; done  # set-u-safe: seeded with ARCH
  success "$joined"
}

# ── Orchestrator ─────────────────────────────────────────────────────────────
run_preflight() {
  if [[ -n "${TRACEBLOC_SKIP_PREFLIGHT:-}" ]]; then
    info "Preflight checks skipped (TRACEBLOC_SKIP_PREFLIGHT set)."
    return 0
  fi
  PF_HARD_FAIL=0
  # Run the arch/CPU/RAM/disk checks in quiet-success mode: on the happy path they
  # print nothing and we collapse them into ONE summary line below; a warning or
  # hard-fail still prints its specific ⚠/✖. '|| true' so a single check returning
  # non-zero can't trip set -e before the others run — PF_HARD_FAIL is the truth.
  PF_QUIET_SUCCESS=1
  _pf_arch         || true
  _pf_cpu          || true
  _pf_memory       || true
  _pf_disk         || true
  # The combined hardware line — only when nothing hard-failed so far.
  if [[ "$PF_HARD_FAIL" -eq 0 ]]; then _pf_hw_summary_line; fi
  # Connectivity (own spinner + combined "Connected:" line) and storage
  # ("Local storage (…)") each print their own always-on summary line.
  _pf_connectivity || true
  _pf_storage_type || true
  unset PF_QUIET_SUCCESS

  if [[ "$PF_HARD_FAIL" -gt 0 ]]; then
    echo ""
    error "Preflight failed — resolve the ✖ item(s) above and re-run. (Override at your own risk with TRACEBLOC_SKIP_PREFLIGHT=1.)"
  fi
}
