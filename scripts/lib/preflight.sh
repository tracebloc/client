#!/usr/bin/env bash
# =============================================================================
#  preflight.sh — fail-fast environment checks (arch, egress, disk, RAM, CPU)
#
#  Runs before any install/cluster work. Each check prints a ✔/⚠/✖ line; hard
#  failures are AGGREGATED so the user sees every problem at once, then we exit
#  ONCE with a summary. The goal: a run that can't succeed fails in seconds with
#  a precise, actionable reason instead of a cryptic crash minutes in.
#
#  Escape hatches:
#    TRACEBLOC_SKIP_PREFLIGHT=1   skip all checks
#    TRACEBLOC_ALLOW_ARM64=1      proceed on arm64 without checking whether the
#                                 engine this install gets is the amd64-only one
#    TRACEBLOC_ALLOW_NETWORK_FS=1 proceed when HOST_DATA_DIR is on NFS/CIFS/SMB (DB may corrupt)
#    PF_MIN_MEM_GB / PF_MIN_CPU / PF_MIN_DISK_GB   lower the hard floors (CI / odd sites)
#
#  This file is side-effect-safe to source (defaults + function defs only).
# =============================================================================

# Thresholds (overridable via env — for unusual sites or tests).
# RAM floors are derived from the real stack, not guessed: the always-on control
# plane requests ~2.1 GiB, + k3s/k3d ~0.8 + OS/Docker ~0.7 ≈ ~4.4 GiB just to stay
# Online on a single-node (k3d) install — so below 5 GiB it boots then OOMs (the
# hard floor, PF_MIN_MEM_GB). "Comfortable to run" is no longer a typed 8: it is
# PF_WARN_MEM_GB, the VM budget the smallest training rung needs beside the
# platform, derived below from the generated VM constant -- which moves with the
# measured records under scripts/spec/node-reservation/, so no figure is typed
# here. 16 GiB is recommended to train locally (a job's limit is ~8 GiB+).
# Settings naming (backend#3846): each PF_* threshold below is overridable as
# TRACEBLOC_PF_* -- a non-empty canonical wins, else the legacy PF_* (remove_by
# 2026-12-31), else the default -- resolved into the PF_* variable this file reads.
if [[ -n "${TRACEBLOC_PF_MIN_DISK_GB:-}" ]]; then PF_MIN_DISK_GB="$TRACEBLOC_PF_MIN_DISK_GB"; fi
PF_MIN_DISK_GB="${PF_MIN_DISK_GB:-10}"     # hard-fail below this (Linux) — base images alone need >5
if [[ -n "${TRACEBLOC_PF_WARN_DISK_GB:-}" ]]; then PF_WARN_DISK_GB="$TRACEBLOC_PF_WARN_DISK_GB"; fi
PF_WARN_DISK_GB="${PF_WARN_DISK_GB:-20}"   # warn below this
if [[ -n "${TRACEBLOC_PF_MIN_MEM_GB:-}" ]]; then PF_MIN_MEM_GB="$TRACEBLOC_PF_MIN_MEM_GB"; fi
# Whether the floor was SET rather than defaulted: the default is replaced by the
# derived run floor below (_pf_run_floor_mib -- the host on Linux, backend#5601;
# the VM on macOS and Windows, client-dev#2105), and an explicit value is the
# documented escape hatch that still wins.
_PF_MIN_MEM_GB_EXPLICIT=0
if [[ -n "${PF_MIN_MEM_GB:-}" ]]; then _PF_MIN_MEM_GB_EXPLICIT=1; fi
PF_MIN_MEM_GB="${PF_MIN_MEM_GB:-5}"        # hard-fail below this (unless overridden, the derived run floor replaces it; warn on a Mac/Win host)
_PF_MIN_MEM_GB_RESOLVED="$PF_MIN_MEM_GB"
# ── VM budget for the smallest training rung (GENERATED by scripts/gen-vm-budget-embed.sh — do not hand-edit) ──
# rung + kubelet reservation + k3s addons + control plane + CronJob transient, in
# bytes (backend#2460, RFC-BACKEND-664 §L0.1/§P4). Kept honest by
# `gen-vm-budget-embed.sh --check` in `make drift`.
_TB_VM_MIN_MEM_BYTES=9911140352
# The Linux HARD floor: Linux kubelet carve-out + the platform's own pods (contract
# `overhead`) + the least a training run is worth scheduling (contract `floor`)
# (backend#5601). Below it no run can ever schedule on this host.
_TB_LINUX_MIN_MEM_BYTES=7482638336
# The same floor over the macOS and the Windows carve-out, graded on the VM beneath
# the node (client-dev#2105). Below it no run can ever schedule in that VM.
_TB_DARWIN_MIN_MEM_BYTES=7348420608
_TB_WINDOWS_MIN_MEM_BYTES=7046430720
# ── end generated VM budget ───────────────────────────────────────────────────
# The warn tier is DERIVED from that constant: below it the smallest training
# run (XS, 4 GiB) cannot schedule beside the platform, so "comfortable to run" is
# now a number with a source rather than a feeling about 8. Ceiling to whole GB
# because that is the unit the macOS node's --memory and .wslconfig take. The `8`
# fallback is the pre-derivation value and is UNREACHABLE while the drift guard
# is green: an unpopulated embed is a finding there, never a quiet 8 here.
_pf_vm_min_gb() {
  local b="${_TB_VM_MIN_MEM_BYTES:-0}"
  if [[ ! "$b" =~ ^[0-9]+$ ]] || (( b <= 0 )); then printf '8'; return 0; fi
  printf '%s' "$(( (b + 1024 * 1024 * 1024 - 1) / (1024 * 1024 * 1024) ))"
}
# The platform family whose run floor grades this machine: the Mac's VM, the WSL2
# VM (Windows; the bash twin runs inside it), or a Linux host. Nothing elsewhere.
_pf_run_floor_family() {
  case "${OS:-}" in
    Darwin) printf 'darwin' ;;
    Linux)
      if declare -F _probe_wsl >/dev/null 2>&1 && _probe_wsl; then printf 'windows'; else printf 'linux'; fi ;;
    *) return 1 ;;
  esac
}
# The HARD run floor in MiB, ceiled, from the embed above for a family (default:
# this machine's) -- or nothing (exit 1) when PF_MIN_MEM_GB was set or changed
# after load (the escape hatch), the family has no row, or the embed is
# unpopulated (the drift guard makes that unreachable; the typed floor then
# grades, as before). No grace: the kubelet sizes allocatable from MemTotal, so a
# host or VM a MiB under this cannot fit the run however its total is rounded.
_pf_run_floor_mib() {
  local fam="${1:-}" b
  [[ -n "$fam" ]] || fam="$(_pf_run_floor_family)" || return 1
  case "$fam" in
    linux)   b="${_TB_LINUX_MIN_MEM_BYTES:-0}" ;;
    darwin)  b="${_TB_DARWIN_MIN_MEM_BYTES:-0}" ;;
    windows) b="${_TB_WINDOWS_MIN_MEM_BYTES:-0}" ;;
    *) return 1 ;;
  esac
  if (( ${_PF_MIN_MEM_GB_EXPLICIT:-0} )) || [[ "$PF_MIN_MEM_GB" != "${_PF_MIN_MEM_GB_RESOLVED:-$PF_MIN_MEM_GB}" ]]; then return 1; fi
  if [[ ! "$b" =~ ^[0-9]+$ ]] || (( b <= 0 )); then return 1; fi
  printf '%s' "$(( (b + 1024 * 1024 - 1) / (1024 * 1024) ))"
}
_pf_linux_run_floor_mib() { _pf_run_floor_mib linux; }
# THE FLOOR EVERY MEMORY GATE GRADES A MemTotal AGAINST, in MiB: the derived run
# floor where there is one, else the typed PF_MIN_MEM_GB less the guest grace
# (the pre-derivation rule, and the escape hatch's). Arg: family (default: this
# machine's) -- _macos_vm_mem_gb names `darwin`, since it only ever sizes the macOS
# node's VM.
_pf_vm_floor_mib() {
  local f
  if f="$(_pf_run_floor_mib "${1:-}")"; then printf '%s' "$f"
  else printf '%s' "$(( PF_MIN_MEM_GB * 1024 - PF_VM_MEM_GRACE_MIB ))"; fi
}
# The same floor as the whole-GB size to CONFIGURE (the macOS node's --memory and
# .wslconfig take whole GB): ceil((floor + grace) / 1024), so a VM set to it
# clears the floor after the guest shortfall, and a VM the floor refuses always
# displays (_pf_display_gb_from_mib) below it. The typed floor maps back to
# exactly PF_MIN_MEM_GB.
_pf_vm_floor_gb() {
  local m; m="$(_pf_vm_floor_mib "${1:-}")"
  printf '%s' "$(( (m + PF_VM_MEM_GRACE_MIB + 1023) / 1024 ))"
}
# The least Docker budget a hint may name, and a host must spare beside the OS
# reserve: the VM's floor on a Mac or under WSL2. On native Linux the daemon sees the
# host, which _pf_memory already grades against the derived floor directly, so the
# reserve arithmetic keeps the typed floor it had before client-dev#2105.
_pf_budget_floor_gb() {
  if [[ "$(_pf_run_floor_family 2>/dev/null)" == linux ]]; then printf '%s' "$PF_MIN_MEM_GB"
  else _pf_vm_floor_gb; fi
}
# What a budget below that floor costs, worded once for every gate: the derived
# floor is about one training run, the typed one about the client itself.
_pf_vm_floor_words() {
  if _pf_run_floor_mib "${1:-}" >/dev/null; then
    printf 'below the %s GB one training run needs beside the tracebloc platform' "$(_pf_vm_floor_gb "${1:-}")"
  else
    printf 'below the %s GB the client needs; it will OOM' "$PF_MIN_MEM_GB"
  fi
}
# The family the RUNTIME graders (_pf_runtime_mem_status, _pf_recheck_runtime_mem)
# hold Docker's budget to after native Linux's run floor: the VM's family on a Mac
# or under WSL2, and `typed` on native Linux. Native Linux is graded FIRST against
# its run floor through _pf_runtime_run_floor_mib (client-dev#2113), so `typed` is
# what remains for it -- the typed floor, which governs only under the escape hatch.
_pf_runtime_floor_family() {
  local fam
  fam="$(_pf_run_floor_family 2>/dev/null)" || fam=typed
  [[ "$fam" == linux ]] && fam=typed
  printf '%s' "$fam"
}
# MiB as GB to one decimal, rounded DOWN (a machine's figure) or UP (a floor's), so
# a refused machine never reads as large as the floor that refused it.
_pf_tenths_gb() {
  local mib="$1" dir="$2" t
  if [[ "$dir" == up ]]; then t=$(( (mib * 10 + 1023) / 1024 )); else t=$(( mib * 10 / 1024 )); fi
  printf '%s.%s' "$(( t / 10 ))" "$(( t % 10 ))"
}
if [[ -n "${TRACEBLOC_PF_WARN_MEM_GB:-}" ]]; then PF_WARN_MEM_GB="$TRACEBLOC_PF_WARN_MEM_GB"; fi
PF_WARN_MEM_GB="${PF_WARN_MEM_GB:-$(_pf_vm_min_gb)}"  # warn below this: the smallest training rung fits (derived)
if [[ -n "${TRACEBLOC_PF_REC_MEM_GB:-}" ]]; then PF_REC_MEM_GB="$TRACEBLOC_PF_REC_MEM_GB"; fi
PF_REC_MEM_GB="${PF_REC_MEM_GB:-16}"       # recommended to train locally (copy only, not a gate)
if [[ -n "${TRACEBLOC_PF_OS_RESERVE_GB:-}" ]]; then PF_OS_RESERVE_GB="$TRACEBLOC_PF_OS_RESERVE_GB"; fi
PF_OS_RESERVE_GB="${PF_OS_RESERVE_GB:-2}"  # RAM to leave the OS — recommendations clamp at physical − this (#428)
# A guest VM's reported MemTotal runs a few hundred MiB below its CONFIGURED size
# (kernel/reserved). The runtime recheck sees the GUEST figure, so it tolerates this
# much below the floor — otherwise a Docker Desktop VM set to exactly the documented
# floor would hard-fail on the guest shortfall, making the effective floor a GB higher
# than we tell people (#513 reviewer). 512 MiB comfortably covers the observed gap.
if [[ -n "${TRACEBLOC_PF_VM_MEM_GRACE_MIB:-}" ]]; then PF_VM_MEM_GRACE_MIB="$TRACEBLOC_PF_VM_MEM_GRACE_MIB"; fi
PF_VM_MEM_GRACE_MIB="${PF_VM_MEM_GRACE_MIB:-512}"
if [[ -n "${TRACEBLOC_PF_MIN_CPU:-}" ]]; then PF_MIN_CPU="$TRACEBLOC_PF_MIN_CPU"; fi
PF_MIN_CPU="${PF_MIN_CPU:-2}"              # warn below this
if [[ -n "${TRACEBLOC_PF_REC_CPU:-}" ]]; then PF_REC_CPU="$TRACEBLOC_PF_REC_CPU"; fi
PF_REC_CPU="${PF_REC_CPU:-4}"              # recommended (warn) below this

# Non-exiting failure line (common.sh's error() exits; preflight must finish all
# checks first, so failures print here and are recorded in PF_HARD_FAIL). Writes
# to stdout (like warn/success/info) so it stays ordered with the hint() lines
# that follow — only the final aggregated error() writes to stderr.
_pf_fail_line() { echo -e "  ${RED}✖${RESET} $*"; }

# Quiet-success helpers (first-run run-through). run_preflight sets
# PF_QUIET_SUCCESS while the arch/CPU/RAM/disk checks run, so their individual
# ✔ lines are SUPPRESSED and collapsed into one summary line
# ("arch · N CPU cores · N GB memory · N GB free disk"); warnings and hard-fails
# still print. When called directly (the bats suite, or the direct-invocation
# path) the flag is unset and the per-check ✔/info lines print as before, so the
# unit tests that assert on them keep passing. Connectivity + storage print their
# own always-on summary line and so do NOT route through these.
_pf_ok()   { [[ -n "${PF_QUIET_SUCCESS:-}" ]] || success "$*"; }
_pf_note() { [[ -n "${PF_QUIET_SUCCESS:-}" ]] || info "$*"; }

# ── Injectable readers (overridden in bats so checks run without net/df) ─────

# Probe a URL for reachability. Echoes one of: ok|dns|refused|timeout|tls|blocked|nocurl
# (or "http <code>" in strict mode). "Reachable" = any HTTP response (200/401/403 all
# count — TLS + HTTP completed). Pass "strict" as $2 for targets whose CONTENT must
# exist (2xx/3xx only — e.g. the Helm repo index.yaml, where the site root 404s by
# design and plain reachability proves nothing, #385).
# Respects the caller's HTTP(S)_PROXY env (curl picks it up), so a TLS-inspecting
# proxy without its CA surfaces here as 'tls'.
_pf_probe_url() {
  local url="$1" mode="${2:-}" code ec
  has curl || { echo "nocurl"; return 0; }
  code=$(curl_secure -sS -o /dev/null --max-time 8 -w '%{http_code}' "$url" 2>/dev/null) && ec=0 || ec=$?
  if [[ -n "$code" && "$code" != "000" ]]; then
    if [[ "$mode" == "strict" && ! "$code" =~ ^[23] ]]; then echo "http $code"; return 0; fi
    echo "ok"; return 0
  fi
  case "${ec:-1}" in
    6)     echo "dns" ;;
    7)     echo "refused" ;;
    28)    echo "timeout" ;;
    35|60) echo "tls" ;;
    *)     echo "blocked" ;;
  esac
  return 0
}

# Free space in KB on the filesystem holding $1.
_pf_free_kb() { df -Pk "$1" 2>/dev/null | awk 'NR==2 {print $4}'; }

# $1, or its nearest existing parent: the directory whose filesystem will hold a
# path that does not exist yet. Empty when nothing on the way up exists.
_pf_nearest_existing() {
  local p="$1" parent
  while [[ -n "$p" && ! -e "$p" ]]; do
    parent="$(dirname "$p")"
    [[ "$parent" == "$p" ]] && break
    p="$parent"
  done
  [[ -n "$p" && -e "$p" ]] && printf '%s' "$p"
  return 0
}

# Filesystem type holding $1, lower-cased (e.g. ext4, xfs, apfs, overlay, nfs,
# nfs4, cifs, smbfs), or empty if undeterminable. $1 may not exist yet at
# preflight, so walk up to the nearest existing parent. Tries findmnt (util-linux,
# bind-mount aware), then GNU `stat -f` (Linux only — BSD/macOS `stat -f` means
# "format string", not filesystem), then df+mount (portable, incl. macOS).
_pf_fstype() {
  local p t="" mp fstype_out
  p="$(_pf_nearest_existing "$1")"
  [[ -z "$p" ]] && return 0
  if has findmnt; then
    # Capture-then-slice, not `| head -1`: head closes the pipe after line 1 and
    # findmnt takes SIGPIPE, which pipefail turns into 141 — and in an ASSIGNMENT
    # under `set -e` that aborts the installer inside preflight with no message.
    # findmnt prints one line per mount over the target, so a bind-mounted or
    # stacked path is enough (backend#1778; same shape as the mount pipeline below).
    fstype_out="$(findmnt -nro FSTYPE --target "$p" 2>/dev/null || true)"
    t="${fstype_out%%$'\n'*}"
  fi
  if [[ -z "$t" && "$OS" != "Darwin" ]]; then
    t="$(stat -f -c '%T' "$p" 2>/dev/null)"
  fi
  if [[ -z "$t" ]] && has df; then
    mp="$(df "$p" 2>/dev/null | awk 'NR>1 && $NF ~ /^\// {print $NF}' | tail -1)"
    # `awk ... exit` stops reading at the match; `mount` on a container-heavy
    # host prints well past 64 KB, so the pipeline can return 141 and abort the
    # installer inside preflight with no message at all (backend#1778).
    if [[ -n "$mp" ]]; then
      local mount_out
      mount_out="$(mount 2>/dev/null || true)"
      t="$(awk -v m="$mp" 'index($0," on "m" (")>0 {sub(/.* \(/,""); sub(/[,)].*/,""); print; exit}' <<<"$mount_out")"
    fi
  fi
  printf '%s' "$t" | tr '[:upper:]' '[:lower:]'
}

# Memory/CPU as the CONTAINER RUNTIME sees it (the budget the pods actually get).
# On Docker Desktop / WSL2 this is the VM's allocation — smaller than the host and
# the number that matters (a 36 GB machine can cap its Docker VM at 4 GB). Echo
# a single integer, or nothing if the daemon is down / the value is junk — callers
# then fall back to the host reader.
#
# ON NATIVE k3s THE HOST IS THE NODE (TRACEBLOC_SUBSTRATE_RESOLVED=k3s): there is no Docker and no
# VM, so the budget the pods get is the host's own -- /proc/meminfo's MemTotal and
# nproc, through the host readers below, which are the tests' stub seams. Neither
# reader asks Docker anything there.
#
# EXCEPT ON macOS, WHERE k3s RUNS IN A VM on Apple's runtime (slim client 2.1,
# _pf_on_mac_node): the budget is the node's size, never the Mac's (see
# _pf_mac_node_size).
_pf_runtime_mem_kb() {
  if _pf_on_mac_node; then
    local s; s="$(_pf_mac_node_size)" || return 0
    s="${s#* }"; echo $(( ${s%g} * 1024 * 1024 )); return 0
  fi
  if [[ "${TRACEBLOC_SUBSTRATE_RESOLVED:-}" == "k3s" ]]; then _pf_host_mem_kb; return 0; fi
  # Bounded liveness, coreutils-free (#744): _docker_answers bounds through _bounded,
  # which was a no-op on a stock Mac until client-dev#1357; _docker_answers_bounded
  # kills on a deadline via a background PID, with a spinner. Silenced (>/dev/null) — this
  # reader's stdout is captured by the caller, and once the daemon is proven
  # responsive here the --format read below cannot hang.
  has docker && _docker_answers_bounded "probing docker" "${TB_DOCKER_PROBE_TIMEOUT:-10}" >/dev/null 2>&1 || return 0
  local b; b="$(_bounded "${TB_DOCKER_PROBE_TIMEOUT:-10}" docker info --format '{{.MemTotal}}' 2>/dev/null)"
  [[ "$b" =~ ^[0-9]+$ && "$b" -gt 0 ]] && echo $(( b / 1024 ))
  return 0
}
_pf_runtime_ncpu() {
  if _pf_on_mac_node; then
    local s; s="$(_pf_mac_node_size)" || return 0
    echo $(( ${s%% *} + TB_MAC_CT_VM_OWN_CPUS )); return 0
  fi
  if [[ "${TRACEBLOC_SUBSTRATE_RESOLVED:-}" == "k3s" ]]; then _pf_host_ncpu; return 0; fi
  # Coreutils-free bounded liveness, silenced — see _pf_runtime_mem_kb (#744).
  has docker && _docker_answers_bounded "probing docker" "${TB_DOCKER_PROBE_TIMEOUT:-10}" >/dev/null 2>&1 || return 0
  local n; n="$(_bounded "${TB_DOCKER_PROBE_TIMEOUT:-10}" docker info --format '{{.NCPU}}' 2>/dev/null)"
  [[ "$n" =~ ^[0-9]+$ && "$n" -gt 0 ]] && echo "$n"
  return 0
}

# _pf_on_mac_node -- true when k3s runs in a VM on Apple's runtime: native k3s on a Mac
# (slim client 2.1). There the pods' budget, disk and wording are the node's, not
# the Mac's and not Docker's.
_pf_on_mac_node() { [[ "${TRACEBLOC_SUBSTRATE_RESOLVED:-}" == "k3s" && "$OS" == "Darwin" ]]; }

# _pf_mac_node_size -- "<cpus> <N>g", the macOS node's size, from mac-container.sh's
# _mac_ct_node_size: what the node is created with, asked, never restated. Its memory
# is _macos_vm_mem_gb's. The node
# advertises more CPUs than <cpus>: the VM adds vCPUs of its own
# (TB_MAC_CT_VM_OWN_CPUS, mac-container.sh), so the runtime CPU reader adds them back. Fails when mac-container.sh is
# not loaded (it is sourced from 2.1 part 6) or cannot size the node, and the readers
# then answer nothing: the Mac's own figures would overstate the budget, and the fit
# gate says it skipped instead.
_pf_mac_node_size() {
  declare -F _mac_ct_node_size >/dev/null 2>&1 || return 1
  _mac_ct_node_size 2>/dev/null
}

# Total physical RAM of the HOST in KB.
_pf_host_mem_kb() {
  if [[ "$OS" == "Darwin" ]]; then
    local b; b=$(sysctl -n hw.memsize 2>/dev/null) || b=""
    [[ -n "$b" ]] && echo $(( b / 1024 ))
  else
    awk '/^MemTotal:/ {print $2}' /proc/meminfo 2>/dev/null
  fi
}

# Host physical RAM in whole GB (0 when undeterminable). (#428)
_pf_host_mem_gb() {
  local kb; kb="$(_pf_host_mem_kb)"
  [[ "$kb" =~ ^[0-9]+$ ]] || { printf '0'; return 0; }
  printf '%s' "$(( kb / 1024 / 1024 ))"
}

# Clamp a DESIRED memory figure (GB) so a hint never exceeds this machine (#428):
# min(DESIRED, physical − PF_OS_RESERVE_GB), but NEVER below the floor (_pf_budget_floor_gb)
# — the client needs the floor to run, so a hint must never tell the operator to "raise to" a
# sub-floor number (Bugbot). "raise to 16 GB" on a 16 GB Mac is impossible; "raise to
# 4 GB" on a 6 GB Mac is nonsensical (below the floor AND their RAM). Physical unknown/0
# -> DESIRED (can't clamp). Args: DESIRED [physical GB (default: host)].
_pf_clamp_mem_gb() {
  local desired="$1" phys="${2:-$(_pf_host_mem_gb)}" cap floor_gb
  [[ "$phys" =~ ^[0-9]+$ && "$phys" -gt 0 ]] || { printf '%s' "$desired"; return 0; }
  floor_gb="$(_pf_budget_floor_gb)"
  cap=$(( phys - PF_OS_RESERVE_GB )); (( cap < floor_gb )) && cap=$floor_gb
  if (( desired < cap )); then printf '%s' "$desired"; else printf '%s' "$cap"; fi
}

# The memory budget (GB) to give the macOS node's VM (mac-container.sh's
# _mac_ct_node_size), derived from physical RAM (#428): min(half of physical, the
# clamped recommendation), never below the macOS VM floor (_pf_vm_floor_gb darwin:
# the derived run floor, client-dev#2105).
# Physical unknown/0 -> 6 GB, the size the installer gave a Mac's VM before #428
# derived it. Arg: physical GB (default: host).
_macos_vm_mem_gb() {
  local phys="${1:-$(_pf_host_mem_gb)}" half rec budget safe_floor cap
  [[ "$phys" =~ ^[0-9]+$ && "$phys" -gt 0 ]] || { printf '6'; return 0; }
  half=$(( phys / 2 ))
  rec="$(_pf_clamp_mem_gb "$PF_REC_MEM_GB" "$phys")"
  budget=$(( half < rec ? half : rec ))
  # Never size EXACTLY to the floor: the guest MemTotal runs a few hundred MiB below
  # the configured VM size, so a floor-sized VM boots then trips the runtime recheck's
  # sub-floor hard-fail on its OWN choice (#428 Bugbot). Give ≥ 1 GB of headroom above
  # the floor — but never over-commit the host (cap at physical − reserve); a host too
  # small for that gets less, and the recheck then stops it honestly as "too small".
  #
  # AND NEVER BELOW THE SMALLEST TRAINING RUNG'S BUDGET when the host can spare it
  # (RFC-BACKEND-664 §P4: "the ladder is capped by the VM, and must never offer a
  # rung the VM cannot honour"). PF_WARN_MEM_GB is that budget, DERIVED from the
  # generated VM constant above — so a fresh VM on a 16 GB Mac is sized to what the
  # 4 GiB rung needs beside the platform (the constant's figure, whatever the
  # records make it; it moved from 9 to 10 GB when the Windows record landed), not
  # to the stay-Online floor
  # plus a GB (6), which runs the client and sizes every run below the rung. The
  # half-of-physical rule still wins above it.
  #
  # AND ONLY WHEN THE HOST CAN SPARE THE WHOLE BUDGET (tracebloc-review on #1090).
  # Applied unconditionally, the rung floor raised a 9 or 10 GB Mac to its cap (7
  # or 8 GB): RAM taken from macOS that the rung still cannot use, so the host paid
  # and got the same "training cannot schedule" warning as before. When the cap is
  # below the rung the #428 size stands.
  #
  # AND NEVER BELOW THE RUN FLOOR (client-dev#2105). PF_MIN_MEM_GB + 1 sized an 8 GB
  # Mac to a 6 GB VM, under the 6.6 GiB one training run needs beside the platform:
  # the install went through and no run could ever schedule. The derived floor is
  # already a configured size (its grace is in it), so it needs no extra GB; the
  # host cap below still wins, and a Mac whose cap is under it gets that cap and an
  # honest refusal from the recheck rather than a VM that silently cannot train.
  local floor_gb; floor_gb="$(_pf_vm_floor_gb darwin)"
  safe_floor=$(( PF_MIN_MEM_GB + 1 ))
  (( floor_gb > safe_floor )) && safe_floor=$floor_gb
  cap=$(( phys - PF_OS_RESERVE_GB ))
  if [[ "${PF_WARN_MEM_GB:-}" =~ ^[0-9]+$ ]] && (( PF_WARN_MEM_GB > safe_floor )) && (( cap >= PF_WARN_MEM_GB )); then
    safe_floor=$PF_WARN_MEM_GB
  fi
  (( budget < safe_floor )) && budget=$safe_floor
  (( budget > cap )) && budget=$cap
  (( budget < 1 )) && budget=1
  printf '%s' "$budget"
}

# Logical CPU count of the HOST.
_pf_host_ncpu() {
  if [[ "$OS" == "Darwin" ]]; then
    sysctl -n hw.ncpu 2>/dev/null
  else
    nproc 2>/dev/null || getconf _NPROCESSORS_ONLN 2>/dev/null
  fi
}

# Available (free) RAM right now, KB — Linux only (for the busy-shared-VM warn).
_pf_avail_mem_kb() { awk '/^MemAvailable:/ {print $2}' /proc/meminfo 2>/dev/null; }

# Selectors: prefer the runtime view, fall back to the host. The checks (and the
# bats numeric test) call these names; they always emit exactly one integer.
#
# There is deliberately NO _pf_total_mem_kb "prefer the runtime" memory selector
# (#417): conflating the two numbers made the SAME machine report "16 GB (host)"
# on a cold run and "6 GB (Docker VM)" on a warm one. Memory has two distinct
# truths and each caller must name the one it means — _pf_host_mem_kb for a
# hardware fact, _pf_runtime_mem_kb for the budget the pods actually get.
# CPU keeps the fallback selector: there is no equivalent advice split.
_pf_ncpu()         { local v; v="$(_pf_runtime_ncpu)";   [[ -n "$v" ]] && { echo "$v"; return 0; }; _pf_host_ncpu; }

# The ONE copy AND the one grading threshold for the Docker-budget line (#417),
# used by BOTH _pf_memory (Docker already up on a warm re-run) and the post-Docker
# recheck. The two used to print diverging text for the identical condition, and
# because they also compared against DIFFERENT thresholds — the helper against the
# clamped target, the recheck against the raw PF_WARN_MEM_GB — one run could print
# "✔ Docker's memory budget: 6 GB" and then "⚠ recommended ≥ 6 GB" about the very
# same budget (Bugbot #445 r2). Grading lives here only.
#
# Takes MiB, not GB, so it uses the SAME PF_VM_MEM_GRACE_MIB tolerance as the
# recheck: a VM configured to exactly the documented floor reports a few hundred
# MiB less as guest MemTotal, and rounding that to whole GB first would misgrade it
# as sub-floor.
#
# WARN-ONLY by design; the sub-floor HARD-FAIL stays in _pf_recheck_runtime_mem,
# the only place the real VM size is known (#428/#513). Sets
# PF_RUNTIME_MEM_WARNED so one run never warns twice about the same budget — that
# latch suppresses a duplicate WARNING only and must never gate the hard-fail.
# Args: the runtime budget in MiB, and optionally "quiet_ok" to suppress the ✔
# line when the budget is fine — the post-Docker recheck passes it so a healthy
# install doesn't print the same ✔ twice (preflight already said it on a warm run).
# True when the MACHINE cannot give Docker the floor while leaving the OS its
# reserve. No Docker setting fixes that, so both the machine line (_pf_memory) and
# the budget remedy (_pf_runtime_mem_status) must reach the same verdict from ONE
# definition — a 5-6 GB host was being graded "enough to run" on one line and told
# to "use a larger machine" two lines later, in the same preflight (Bugbot #445 r3).
# Displayed GB for a CONFIGURED memory size, given MiB. ONE definition: this
# figure is rendered in four places (_pf_memory, _pf_runtime_mem_status,
# _pf_recheck_runtime_mem, _pf_hw_summary_line) and every review round on this PR
# found another pair of them disagreeing — most recently a collapsed hardware
# summary printing a different size from the memory line in the same preflight
# (Bugbot #445 r6).
#
# The grace compensates for a guest reporting MemTotal a few hundred MiB below the
# size it was configured with, so it belongs on anything claiming "this is how much
# memory X has". It deliberately does NOT belong on live measurements
# (MemAvailable) — inflating those would hide a real shortage — nor on
# _pf_host_mem_gb, which reports physical RAM needing no compensation and is the
# input _pf_host_too_small_for_floor grades (on native Linux, in MiB against the
# ungraced run floor -- client-dev#2181).
_pf_display_gb_from_mib() {
  echo $(( ( ${1:-0} + PF_VM_MEM_GRACE_MIB ) / 1024 ))
}

_pf_host_too_small_for_floor() {
  local host_gb="${1:-}" run_floor_mib
  [[ "$host_gb" =~ ^[0-9]+$ ]] || return 1
  (( host_gb > 0 )) || return 1
  # Under WSL2 the bash twin runs INSIDE the VM, so MemTotal is the VM's own size
  # (the .wslconfig default is half the Windows host), never the host's: reserve
  # arithmetic on it called a VM sitting exactly on the floor too small and
  # answered "use a larger machine" where the remedy is raising the VM
  # (client-dev#2124, Bugbot). The Windows host cannot be told from inside the
  # VM, which is "not too small"; the retired PowerShell core graded it, and the
  # distro path has no host-side grade yet (client-dev#1810).
  [[ "$(_pf_run_floor_family 2>/dev/null)" == windows ]] && return 1
  # Native Linux with the run floor resolved (client-dev#2113): the host is held to
  # the run floor in MiB with no OS reserve and no grace -- the very comparison
  # _pf_memory hard-fails on -- so the two never disagree. Grading it against the
  # rounded remedy instead (floor + grace, ceil'd to GB) called an 8 GB box whose
  # MemTotal reads 7.7 GB "too small, use a larger machine" two lines after
  # _pf_memory had graded it "enough to run" (client-dev#2181). The remedy stays
  # givable there: on Linux it is a VM or cgroup limit, which may be set past the
  # MemTotal the guest reports. The precise MemTotal is read when it agrees with the
  # GB argument; otherwise the argument is all there is (a caller grading a figure
  # of its own). A Mac or WSL2 VM keeps the reserve arithmetic against its VM floor
  # (client-dev#2105).
  if run_floor_mib="$(_pf_runtime_run_floor_mib)"; then
    local host_mib=$(( host_gb * 1024 )) kb
    kb="$(_pf_host_mem_kb)"
    [[ "$kb" =~ ^[0-9]+$ ]] && (( kb / 1024 / 1024 == host_gb )) && host_mib=$(( kb / 1024 ))
    (( host_mib < run_floor_mib ))
    return
  fi
  (( host_gb - PF_OS_RESERVE_GB < $(_pf_budget_floor_gb) ))
}

# The run floor (MiB) a native Linux DOCKER BUDGET is graded against, or nothing
# (exit 1) off native Linux -- a Mac, or WSL2, which reports OS=Linux but is graded
# on the Windows VM's floor (client-dev#2105) -- or when the floor does not resolve
# (the escape hatch). _pf_memory grades the HOST against it; on Linux the daemon's
# budget can still sit below the host (Docker Desktop for Linux, a VM or cgroup
# limit), and a budget between the typed floor and this one installed fine and then
# never scheduled a run (client-dev#2113). Both runtime graders read it here, so
# they agree.
_pf_runtime_run_floor_mib() {
  [[ "$(_pf_run_floor_family 2>/dev/null)" == linux ]] || return 1
  _pf_linux_run_floor_mib
}

# The ONE remedy size for a budget under that floor, in whole GB (the unit a limit
# takes): the clamped rung budget, raised to the run floor when the clamp sits under
# it -- a remedy below the floor just named is no remedy. The floor is graded on the
# guest's MemTotal with no grace, and a VM or Docker Desktop guest reports up to
# PF_VM_MEM_GRACE_MIB under its configured size, so the size quoted is the floor
# PLUS that grace: a VM set to exactly the quoted figure clears the floor, rather
# than failing the same check again (Bugbot on client-dev#2115). Arg: the run
# floor in MiB.
_pf_runtime_run_target_gb() {
  local floor_gb warn_eff
  floor_gb=$(( (${1:-0} + PF_VM_MEM_GRACE_MIB + 1023) / 1024 ))
  warn_eff="$(_pf_clamp_mem_gb "$PF_WARN_MEM_GB")"
  if (( warn_eff > floor_gb )); then printf '%s' "$warn_eff"; else printf '%s' "$floor_gb"; fi
}

# What a Docker budget below the smallest training rung's budget COSTS, worded
# once for every rung warning. It used to say "training pods stay Pending", and on
# today's admission path nothing does that (backend#5025 O-20: a CLM run on a
# 16 GB Mac at an 8 GB VM started in a minute and trained). The installer sizes
# the run envelope to what the node can hold (_fit_training_envelope ->
# _fit_verdict, verdict `reduced`) and jobs-manager admits at that envelope, so
# the real cost is memory per run, not scheduling. Pending stays possible only for
# a size a human pinned, which _fit_verdict reports itself (`pinned-over`).
_pf_below_rung_words() {
  printf 'below it each training run gets less memory than the smallest training size (4 GiB), so a larger model can run out of memory'
}

# The same consequence for the arms that name what the machine can spare: there is
# no budget left to point "below it" at, so the sentence names the cost directly.
_pf_spare_rung_words() {
  printf 'each training run gets less memory than the smallest training size (4 GiB), so a larger model can run out of memory'
}

# "CAN SPARE" UNDER WSL2 IS THE VM ITSELF (client-dev#2158, Bugbot on client-dev#2157).
# MemTotal there is the WSL2 VM, not the Windows host: the host's OS reserve lives
# outside it, and _pf_host_too_small_for_floor does not grade the Windows host (the
# retired PowerShell core did; the distro path has no host-side grade yet).
# Elsewhere it is host RAM less the OS reserve. Never the floor-lifted clamp
# (client-dev#2124). Args: the clamped figure, the host/VM GB.
_pf_spare_gb() {
  local spare="$1" phys="$2"
  if ! [[ "$phys" =~ ^[0-9]+$ ]] || (( phys <= 0 )); then printf '%s' "$spare"; return 0; fi
  if [[ "$(_pf_run_floor_family 2>/dev/null)" == windows ]]; then
    # Under the need the arm names, the whole VM is the honest figure; at or over
    # it the clamped figure stays, so the sentence cannot contradict itself.
    if (( phys < PF_WARN_MEM_GB )); then spare="$phys"; fi
  elif (( phys - PF_OS_RESERVE_GB < spare )); then
    spare=$(( phys - PF_OS_RESERVE_GB ))
  fi
  printf '%s' "$spare"
}

_pf_runtime_mem_status() {
  local rt_mib="$1" quiet_ok="${2:-}" rt_gb warn_eff rec_eff host_gb target_gb what="Docker's memory budget"
  # On macOS k3s runs in Apple's VM, sized by the installer's own rule
  # (_pf_mac_node_size): the line names the node, and no Docker setting is a remedy.
  ! _pf_on_mac_node || what="The node's memory"
  # Report the CONFIGURED size, not the guest-visible one. A VM asked for N GB
  # reports a few hundred MiB less as MemTotal (kernel + firmware reservations),
  # so plain rt_mib/1024 showed a VM set to exactly the documented floor as one
  # GB BELOW it — graded correctly by the grace-aware thresholds below, but
  # displayed as if sub-floor, which reads as a contradiction. Adding the same
  # grace before the division, (mib + grace) / 1024, recovers the configured
  # figure (Bugbot #445 r3).
  rt_gb="$(_pf_display_gb_from_mib "$rt_mib")"
  warn_eff="$(_pf_clamp_mem_gb "$PF_WARN_MEM_GB")"
  rec_eff="$(_pf_clamp_mem_gb "$PF_REC_MEM_GB")"
  # Native Linux: the derived run floor, no grace (as in _pf_memory -- the kubelet
  # sizes allocatable from this MemTotal), so this line and the recheck's hard-fail
  # agree (client-dev#2113). A Mac or WSL2 VM: its own family's floor (client-dev#2105).
  local rt_fam run_floor_mib=""
  rt_fam="$(_pf_runtime_floor_family)"
  run_floor_mib="$(_pf_runtime_run_floor_mib)" || run_floor_mib=""
  if [[ -n "$run_floor_mib" ]] && (( rt_mib < run_floor_mib )); then
    warn "${what}: $(_pf_tenths_gb "$rt_mib" down) GB — below the $(_pf_tenths_gb "$run_floor_mib" up) GB one training run needs beside the tracebloc platform; no run can schedule."
    target_gb="$(_pf_runtime_run_target_gb "$run_floor_mib")"
  elif (( rt_mib < $(_pf_vm_floor_mib "$rt_fam") )); then
    warn "${what}: ${rt_gb} GB — $(_pf_vm_floor_words "$rt_fam")."
    # Sub-floor is the ONE condition where _pf_recheck_runtime_mem also hard-fails
    # (the latch suppresses a duplicate warning, never the hard-fail), so this
    # remedy has to quote the SAME size that failure quotes or one install prints
    # two different targets for one problem — the diverging-copy bug this change
    # exists to remove, which survived on exactly this path (Bugbot #445 r3).
    target_gb="$warn_eff"
  # The WARN threshold carries the grace too, not just the floor one. The shown
  # figure is now (mib + grace)/1024, so grading this branch on the raw threshold
  # reopened the same self-contradiction one boundary up: every budget in
  # [warn*1024 - grace, warn*1024) — 7680..8191 MiB at warn 8, a band common VM
  # defaults land in — printed "budget: 8 GB — recommended ≥ 8 GB".
  # With both the display and both thresholds pivoting on the grace, shown == target
  # implies the ✔ branch, so no displayed number can contradict its own grade.
  elif (( rt_mib < warn_eff * 1024 - PF_VM_MEM_GRACE_MIB )); then
    # THE NEED IS THE DERIVED RUNG BUDGET; THE CLAMP IS WHAT THIS MACHINE CAN SPARE
    # (Bugbot on client#1085). `warn_eff` is PF_WARN_MEM_GB clamped to host RAM minus
    # the OS reserve, so on an 8 GB host it reads 6 — and printing it as "the
    # smallest run needs 6 GB" told that host the 4 GiB rung fits in a budget it
    # already had, while the rung still would not schedule. The sentence now
    # interpolates the unclamped figure.
    # AND NO "Give Docker N GB" REMEDY WHEN THE CLAMP BIT (Bugbot, round 3): a
    # target the same line has just called too small to hold a training run is
    # not a remedy, so none is printed on this case. The
    # warn's own last sentence is the whole of the advice; the latch below still
    # sets, so the recheck does not say it twice.
    if (( warn_eff < PF_WARN_MEM_GB )); then
      # "CAN SPARE" IS NEVER THE FLOOR-LIFTED CLAMP (Bugbot on client-dev#2124).
      # _pf_clamp_mem_gb lifts its cap to the VM floor (8 GB on a Mac, 9 under
      # WSL2) so a sizing never lands below it; quoting that lifted figure here
      # told an 8 GB host it could spare 8 or 9 GB. _pf_spare_gb says what it is:
      # host RAM less the OS reserve, or under WSL2 the VM itself (client-dev#2158).
      local spare_gb host_gb
      host_gb="$(_pf_host_mem_gb)"
      spare_gb="$(_pf_spare_gb "$warn_eff" "$host_gb")"
      warn "${what}: ${rt_gb} GB — enough to run the client; the smallest training run (4 GiB) needs a ${PF_WARN_MEM_GB} GB budget once the kubelet reservation, k3s addons, control plane and CronJobs are counted, and this machine can spare at most ${spare_gb} GB, so $(_pf_spare_rung_words)."
      target_gb=""
    else
      warn "${what}: ${rt_gb} GB — enough to run the client; the smallest training run (4 GiB) needs a ${PF_WARN_MEM_GB} GB budget once the kubelet reservation, k3s addons, control plane and CronJobs are counted (${rec_eff} GB to train comfortably); $(_pf_below_rung_words)."
      # THE REMEDY NAMES THE NEED, NOT THE COMFORTABLE FIGURE (backend#5025 O-14).
      # The sentence above already names the comfortable figure, once; every remedy
      # for this condition quotes the rung budget, as the sub-floor branch does.
      target_gb="$warn_eff"
    fi
  else
    [[ -n "$quiet_ok" ]] || _pf_ok "${what}: ${rt_gb} GB"
    return 0
  fi
  # A machine that cannot reach the floor even with the OS reserve honoured is too
  # small for tracebloc no matter how Docker is configured, so a "give Docker N GB"
  # remedy is a dead end that asks for more than the machine has (Bugbot #445 r2).
  # Say so plainly instead; the recheck's own host-too-small branch then stops
  # the install honestly (#444).
  host_gb="$(_pf_host_mem_gb)"
  [[ "$what" == "Docker's memory budget" ]] || target_gb=""
  if [[ -z "$target_gb" ]]; then
    :   # the clamped warn above carries its own advice; no concrete target exists to print
  elif _pf_host_too_small_for_floor "$host_gb"; then
    if [[ -n "$run_floor_mib" ]]; then
      hint "This machine has ${host_gb} GB of RAM total, less than the $(_pf_runtime_run_target_gb "$run_floor_mib") GB Docker budget one training run needs beside the tracebloc platform. Use a larger machine."
    else
      hint "This machine has ${host_gb} GB of RAM total; the client needs a $(_pf_budget_floor_gb) GB Docker budget and the OS needs ~${PF_OS_RESERVE_GB} GB. Free up memory or use a larger machine."
    fi
  else
    # No Docker Desktop dead end on Linux (Bugbot #445): headless/engine-only
    # boxes have no Desktop UI — a low budget there is the machine's RAM or a
    # VM/cgroup limit.
    hint "Give Docker ${target_gb} GB: on Linux this budget is the machine's RAM or a VM/cgroup limit — raise that limit or free memory, then restart Docker."
  fi
  PF_RUNTIME_MEM_WARNED=1
  return 0
}

